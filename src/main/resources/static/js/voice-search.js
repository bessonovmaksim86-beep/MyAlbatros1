/**
 * Голосовой ввод в поиск.
 *
 * Кнопка-микрофон встаёт внутрь поля поиска. По нажатию запускается
 * Web Speech API — распознавание русской речи, встроенное в браузер.
 * Распознанный текст нормализуется и попадает в поле, а дальше работает
 * штатный поиск: скрипт только досылает событиe 'input', поэтому
 * debounce, отмена прежних запросов и группировка выдачи остаются
 * нетронутыми, а сервер не знает, что запрос набрали голосом.
 *
 * Нормализация — суть скрипта. Распознаватель слышит речь как слова,
 * а номера в системе записаны символами: «ЗП-2026-005» диктуется как
 * «зэ пэ две тысячи двадцать шесть ноль ноль пять», и без разбора это
 * бессмысленная строка. Словарь ниже превращает названия букв в буквы,
 * а произнесённые числа — в цифры.
 *
 * Требуется защищённый источник: браузер отдаёт SpeechRecognition
 * только на https или localhost. Вне поддержки скрипт молча не показывает
 * кнопку, и поиск остаётся текстовым.
 */
(() => {
    'use strict';

    /* ============================================================
       СЛОВАРЬ ПРОИЗНЕСЁННЫХ СИМВОЛОВ
       ============================================================ */

    /*
     * Названия букв — в ВЕРХНЕМ регистре: буквенный префикс номера
     * («ЗНП») обязан сойтись с тем, что хранится в базе. Сервер регистр
     * выравнивает сам (OrderSearch приводит ввод к верхнему), но выдача
     * поиска показывается как есть, и «знп123» в поле выглядело бы
     * опечаткой.
     *
     * Спорные одиночные буквы («и», «а», «у», «о») в словарь не
     * внесены: они совпадают с союзами и предлогами, и «датчик и
     * насос» распался бы на «датчикИнасос». Коды диктуют названиями
     * («ка», «пэ»), где неоднозначности нет.
     */
    const LETTERS = Object.freeze({
        'бэ': 'Б',
        'вэ': 'В',
        'гэ': 'Г',
        'дэ': 'Д',
        'зэ': 'З',
        'ка': 'К',
        'л': 'Л',
        'эл': 'Л',
        'эм': 'М',
        'эн': 'Н',
        'пэ': 'П',
        'эр': 'Р',
        'эс': 'С',
        'тэ': 'Т',
        'у': 'У',
        'эф': 'Ф',
        'ха': 'Х',
        'цэ': 'Ц',
        'ша': 'Ш',
        'ща': 'Щ',
        'че': 'Ч',
        'я': 'Я',
        'через': '-',
        'дефис': '-',
        'тире': '-',
        'запятая': '',
        'пробел': '',

        /*
         * Слитное произношение префиксов. Распознаватель не обязан
         * разбивать аббревиатуру на буквы: «знп» он нередко отдаёт
         * одним словом, и тогда посимвольного разбора не случится.
         */
        'зэпэ': 'ЗП',
        'зэнпэ': 'ЗНП',
        'зээнпэ': 'ЗНП',
        'тэпэ': 'ТП',
        'знп': 'ЗНП',
        'зп': 'ЗП',
        'тп': 'ТП',
        'сп': 'СП'
    });

    /*
     * Разряды чисел: вес, который на них складывается, и признак
     * разряда. Значение «цифра» — вес от 0 до 9: его числом не
     * суммируют (см. joinNumbers).
     */
    const DIGITS = Object.freeze({
        'ноль': 0,
        'ноля': 0,
        'один': 1,
        'одна': 1,
        'одно': 1,
        'два': 2,
        'две': 2,
        'три': 3,
        'четыре': 4,
        'пять': 5,
        'шесть': 6,
        'семь': 7,
        'восемь': 8,
        'девять': 9
    });

    const TENS = Object.freeze({
        'десять': 10,
        'одиннадцать': 11,
        'двенадцать': 12,
        'тринадцать': 13,
        'четырнадцать': 14,
        'пятнадцать': 15,
        'шестнадцать': 16,
        'семнадцать': 17,
        'восемнадцать': 18,
        'девятнадцать': 19,
        'двадцать': 20,
        'тридцать': 30,
        'сорок': 40,
        'пятьдесят': 50,
        'шестьдесят': 60,
        'семьдесят': 70,
        'восемьдесят': 80,
        'девяносто': 90
    });

    const HUNDREDS = Object.freeze({
        'сто': 100,
        'двести': 200,
        'триста': 300,
        'четыреста': 400,
        'пятьсот': 500,
        'шестьсот': 600,
        'семьсот': 700,
        'восемьсот': 800,
        'девятьсот': 900
    });

    /*
     * Множитель старшего разряда: «две тысячи» — это 2 × 1000,
     * поэтому слово несёт не значение, а умножитель.
     */
    const SCALES = Object.freeze({
        'тысяча': 1000,
        'тысячи': 1000,
        'тысяч': 1000
    });

    /*
     * Словом «год» диктуют середину номера заказа («ЗП двадцать
     * шесть года»); само слово в номер не входит.
     *
     * Сюда же идут глаголы поиска: «найди насос» и «насос» — один и
     * тот же запрос, а «найди» в наименовании изделия никто не
     * ищет, так что слово только мешает. В отличие от команд
     * перехода (см. COMMAND_HEADS) они не меняют намерение — объект
     * всё так же ищется в выдаче, — поэтому нормализатор их просто
     * выбрасывает, а не разбирает как команду.
     */
    const NOISE = Object.freeze([
        'года',
        'год',
        'группа',
        'заказ',
        'заказа',
        'заказу',
        'найди',
        'покажи',
        'поищи',
        'ищи',

        /*
         * Родовые слова перед номером. Без них фраза «ордер 123»
         * доходит до сервера как есть, а его разбор номера (см.
         * OrderSearch) знает только префикс «ЗП/ЗНП» и чистые цифры:
         * «ордер 123» не похож ни на то, ни на другое, и заказ
         * не нашёлся бы вовсе. Само слово номером не является.
         */
        'ордер',
        'приход'
    ]);

    /* ============================================================
       РАЗБОР ЧИСЕЛ
       ============================================================ */

    /*
     * Проверка: токен — одно из числительных?
     *
     * Вынесен в отдельную функцию, потому что теперь проверка стоит
     * дважды: и в нормализаторе, и в тестах.
     */
    function isNumber(token) {
        return token in DIGITS ||
            token in TENS ||
            token in HUNDREDS ||
            token in SCALES;
    }

    /*
     * Токен — разрядное слово (десятки, сотни, «тысяча»)? Именно
     * его наличие отличает диктовку числом от диктовки по цифрам.
     */
    function isScale(token) {
        return token in TENS || token in HUNDREDS || token in SCALES;
    }

    /*
     * Сложение одного числа: «две тысячи двадцать шесть» → 2026.
     *
     * Накопитель total хранит сумму закрытых разрядов, pending —
     * число, ждущее своего множителя («две» перед «тысячи»). Голый
     * множитель («тысяча») — одна тысяча, поэтому пустой pending
     * считаем единицей.
     */
    function sumNumber(run) {
        let total = 0;
        let pending = 0;

        for (const token of run) {
            if (token in DIGITS) {
                pending += DIGITS[token];
                continue;
            }

            if (token in SCALES) {
                total += (pending === 0 ? 1 : pending) * SCALES[token];
                pending = 0;
                continue;
            }

            total += (TENS[token] || 0) + (HUNDREDS[token] || 0);
        }

        return String(total + pending);
    }

    /*
     * Как произносят номера — и почему одним правилом не обойтись.
     *
     * «ЗП-2026-005» диктуют двумя способами:
     *
     *   числом:   «две тысячи двадцать шесть»  → 2026
     *   цифрами:  «два ноль два шесть»          → 2026
     *
     * Число складывают (2000 + 20 + 6), цифры склеивают («ноль ноль
     * пять» обязано дать «005», а не «5»: ведущие нули — часть
     * номера). Границу между режимами внутри одной цепочки слов
     * задаёт НОЛЬ: по-русски ноль не входит в составное число — не
     * говорят «двадцать ноль», его произносят только как отдельную
     * цифру. Значит ноль ОТКРЫВАЕТ цифровую серию, но лишь тогда,
     * когда до него уже прозвучало разрядное слово: вся цепочка из
     * одних единиц («два ноль два шесть») — это диктовка цифрами, и
     * ноль здесь не граница, а обычная цифра года.
     *
     * Так «двадцать шесть ноль ноль пять» даёт 26 и 005, а не одно
     * 31, — и наоборот, «два ноль два шесть» остаётся одним 2026.
     */
    function splitNumberRun(run) {
        const groups = [];
        let current = [];
        let digits = false;

        for (const token of run) {
            const isZero = token in DIGITS && DIGITS[token] === 0;
            const isPlain = token in DIGITS;

            /*
             * Ноль после разрядного слова начинает цифровую серию:
             * «…двадцать шесть | ноль ноль пять».
             */
            if (isZero && !digits && current.some(isScale)) {
                groups.push({ run: current, digits: false });
                current = [];
                digits = true;
            } else if (!isPlain && digits) {
                /*
                 * Разрядное слово после серии цифр заканчивает её:
                 * «ноль ноль пять | сто два» — это 005 и 102.
                 */
                groups.push({ run: current, digits: true });
                current = [];
                digits = false;
            }

            current.push(token);
        }

        if (current.length) {
            /*
             * Цепочка без единого разрядного слова — диктовка по
             * цифрам, даже если ноль в ней встретился в середине.
             */
            groups.push({
                run: current,
                digits: digits || !current.some(isScale)
            });
        }

        return groups;
    }

    /*
     * Строку числительных превращает в одну или несколько цифровых
     * групп. Каждая группа помечена как число (складывается) или
     * серия цифр (склеивается).
     */
    function joinNumbers(run) {
        return splitNumberRun(run).map(group =>
            group.digits
                ? group.run.map(token => String(DIGITS[token])).join('')
                : sumNumber(group.run)
        );
    }

    /*
     * Превращает распознанную фразу в строку поиска.
     *
     *   «зэ эн пэ две тысячи двадцать шесть ноль ноль пять»
     *                                        → «ЗНП2026 005»
     *   «зэ пэ две тысячи двадцать шесть»     → «ЗП2026»
     *   «датчик давления»                     → «датчик давления»
     *
     * Последнее важно: обычный текстовый запрос не должен испортиться.
     * Слово, не попавшее ни в буквы, ни в числительные, остаётся как
     * есть — поиск по наименованиям работает как работал.
     *
     * РАЗДЕЛИТЕЛИ. Фраза собирается не склейкой всего подряд, а из
     * размеченных частей, и вот почему:
     *
     *   * буквы обязаны идти слитно («ЗНП»): сервер различает тип
     *     заказа по началу первого слова, и «З Н П» разбиралось бы
     *     уже как произвольный набор;
     *   * цифры слитны внутри одной произнесённой группы, но РАЗНЫЕ
     *     группы разделяются пробелом. Сервер режет ввод по
     *     разделителям и склеивает части через «%», поэтому
     *     «ЗНП2026 005» находит «ЗНП-2026-005», а слитное
     *     «ЗНП2026005» не нашло бы ничего — в номере между этими
     *     частями стоит дефис;
     *   * наименования отделяются пробелом от всего: поиск по
     *     справочникам идёт подстрокой как есть, и «датчикдавления»
     *     не нашёл бы ничего.
     */
    function normalize(text) {
        if (!text) {
            return '';
        }

        const tokens = text.toLowerCase()
            .replace(/[.,;:!?«»"']/g, ' ')
            .split(/\s+/)
            .filter(Boolean);

        /*
         * Часть фразы: значение и признак разделимости. Служебные
         * слова («номер», «пробел») в список не попадают вовсе.
         *
         * Цифровой токен, не попавший ни в числовые разряды, ни в
         * буквы, — это произнесённая цифра (например, «5» от
         * распознавателя), и она обязана встать в числовую группу:
         * «ЗП 57» разваливается на «ЗП» и «57», а «57» через
         * пробел сервер склеит как «ЗП%57» и потеряет точное
         * совпадение с «ЗП-2026-057». Поэтому все чистые цифры
         * приклеиваются к предыдущей части, если она — буква.
         */
        const parts = [];
        let i = 0;

        while (i < tokens.length) {
            const token = tokens[i];

            /* Числительные собираются подряд: разбор только всей
             * группы сразу даёт верное число. */
            if (isNumber(token)) {
                const run = [];

                while (i < tokens.length && isNumber(tokens[i])) {
                    run.push(tokens[i]);
                    i++;
                }

                /*
                 * Одна произнесённая цепочка может оказаться несколькими
                 * числами («двадцать шесть ноль ноль пять» — это 26 и
                 * 005). Каждая группа идёт отдельной частью, и сборка
                 * раздельно стоящих частей разделит их пробелом.
                 */
                joinNumbers(run).forEach(value => {
                    parts.push({ value: value, number: true });
                });

                continue;
            }

            if (token in LETTERS) {
                const letter = LETTERS[token];

                if (letter) {
                    parts.push({
                        value: letter,
                        number: false,
                        word: letter === '-'
                    });
                }

                i++;
                continue;
            }

            if (NOISE.indexOf(token) >= 0) {
                i++;
                continue;
            }

            /*
             * Чистая цифра, отданная распознавателем как есть
             * («ЗП 57»), приклеивается к предыдущей ЧАСТИ-БУКВЕ:
             * префикс и номер пишутся слитно, и «ЗП 57» через пробел
             * сервер превратил бы в шаблон, теряющий точное
             * совпадение. К наименованию («рабочее место 7») цифра
             * НЕ приклеивается — там пробел обязателен, иначе код
             * места слился бы со словом. Различает их признак word:
             * у буквы-префикса он false, у наименования true.
             */
            if (/^\d+$/.test(token)) {
                const last = parts[parts.length - 1];

                if (last && !last.number && !last.word) {
                    last.value += token;
                } else {
                    parts.push({ value: token, number: true });
                }

                i++;
                continue;
            }

            /* Наименования и прочие слова — как произнесены. */
            parts.push({ value: token, number: false, word: true });
            i++;
        }

        let out = '';
        let previous = null;

        for (const part of parts) {
            /*
             * Пробел вставляется только между частями, которые обязаны
             * быть раздельны: наименование — с любой стороной, две
             * числовые группы — между собой. Буквы и дефис прилипают.
             */
            const separated = part.word ||
                (previous && (previous.word ||
                    (previous.number && part.number)));

            if (out && separated && !out.endsWith('-')) {
                out += ' ';
            }

            out += part.value;
            previous = part;
        }

        return out
            .replace(/\s+(-)/g, '$1')
            .replace(/(-)\s+/g, '$1')
            .trim();
    }

    /* ============================================================
       КОМАНДЫ ПЕРЕХОДА («открой у меня …»)
       ============================================================ */

    /*
     * Слова, по которым фраза становится КОМАНДОЙ перехода, а не
     * запросом поиска. Разбирается по СЫРОЙ фразе распознавателя:
     * нормализатор вырезает эти слова как служебные, и после
     * нормализации отличить «открой ЗНП 5» от простого «ЗНП 5» было
     * бы нечем.
     */
    const COMMAND_HEADS = [
        'открой',
        'открывай',
        'перейди',
        'покажи'
    ];

    /*
     * Обороты, идущие сразу за словом-командой и ничего не значащие
     * для подбора раздела: «у меня», «в моём интерфейсе».
     *
     * Порядок — от длинного к короткому, и он обязателен: «в» тоже
     * начало «в моём интерфейсе», и срезанное первым короткое
     * оборот оставило бы в термине «моём интерфейсе склад».
     */
    const COMMAND_FILLERS = [
        'в моём интерфейсе',
        'в моем интерфейсе',
        'у меня',
        'мне',
        'у',
        'в'
    ];

    /*
     * Срезает начало строы по префиксу, если тот стоит целым словом.
     *
     * Сравнение с пробелом на конце — не формальность: без него «в»
     * съело бы начало следующего слова, и «открой входной контроль»
     * превратилось бы в «ходной контроль», который уже не находится.
     */
    function stripWordPrefix(text, prefix) {
        if (!text.startsWith(prefix)) {
            return null;
        }

        const rest = text.slice(prefix.length);

        if (rest.length > 0 && !/^\s/.test(rest)) {
            return null;
        }

        return rest.trimStart();
    }

    /*
     * Разбирает сырую фразу на термин команды или null.
     *
     * Термин — то, что осталось после команды и пустых оборотов,
     * ещё НЕ нормализованное: числа и буквы превращает в цифры и
     * латиницу normalize(), и вызывается он уже над остатком.
     *
     * Возвращает null, если команда не в начале фразы: «найди
     * насос» остаётся обычным поиском, и «датчик открой» тоже —
     * иначе любое упоминание в наименовании уводило бы в переход.
     */
    function parseVoiceCommand(rawText) {
        if (!rawText) {
            return null;
        }

        /*
         * Пунктуация распознавателя («открой, ЗНП пять») к термину
         * не относится, а её наличие ломает сравнение с префиксом.
         */
        let text = rawText
            .toLowerCase()
            .replace(/[.,;:!?«»"']/g, ' ')
            .replace(/\s+/g, ' ')
            .trim();

        let matched = false;

        for (const head of COMMAND_HEADS) {
            const rest = stripWordPrefix(text, head);

            if (rest !== null) {
                text = rest;
                matched = true;
                break;
            }
        }

        if (!matched) {
            return null;
        }

        /*
         * Пустые обороты могут идти подряд: «открой у меня в моём
         * интерфейсе склад». Цикл, а не один проход.
         */
        let changed = true;

        while (changed && text) {
            changed = false;

            for (const filler of COMMAND_FILLERS) {
                const rest = stripWordPrefix(text, filler);

                if (rest !== null) {
                    text = rest;
                    changed = true;
                    break;
                }
            }
        }

        return text || null;
    }

    /*
     * Префикс приложения: пустой на корне сервера и «/production»
     * при выкладке в подкаталог.
     *
     * Выводится из адреса endpoint'а, который подставляет Thymeleaf,
     * — тот же приём, что делает data-search-url переносимым. Сервер
     * отдаёт адреса разделов без префикса (так устроены пути в
     * ModuleRoutes), и переход без него ушёл бы в чужой адрес.
     */
    function contextPath(button) {
        const endpoint = button.dataset.voiceUrl || '';
        const anchor = endpoint.indexOf('/voice/command');

        return anchor > 0 ? endpoint.slice(0, anchor) : '';
    }

    /*
     * Раздел, на странице которого стоит страница с поиском.
     *
     * Берётся из адреса страницы, а не из реферера (его браузеры
     * срезают) и не из подписи в шапке (текст меняется вместе с
     * интерфейсом). Первый сегмент пути — это и есть модуль:
     * /warehouse/receiving → warehouse.
     *
     * Пустая строка возвращается на странице поиска (/search) и на
     * рабочем столе: там пользователь ещё не выбрал раздел, и
     * приоритета нет — сервер возьмёт первый доступный кандидат.
     */
    function currentSection(button) {
        let rest = window.location.pathname || '';
        const context = contextPath(button);

        if (context && rest.startsWith(context)) {
            rest = rest.slice(context.length);
        }

        const segment = rest.replace(/^\/+/, '').split('/')[0] || '';

        /*
         * Раздел поиска не является модулем и ничего не значит для
         * выбора раздела: команда с этой страницы не должна тянуть
         * пользователя в /search только потому, что он там стоит.
         */
        return segment === 'search' ? '' : segment;
    }

    /*
     * Отправляет разобранный термин на сервер и уходит по адресу,
     * который сервер посчитал доступным для роли.
     *
     * Сервер решает две вещи, недоступные клиенту: что за объект
     * скрыт за термином и какой раздел этот объект открывает данной
     * роли. Клиент знает только фразу, и угадать права по названию
     * раздела нельзя — поэтому адрес всегда приходит с сервера, а не
     * строится здесь.
     */
    async function runCommand(button, field, term) {
        const endpoint = button.dataset.voiceUrl;

        if (!endpoint) {
            return false;
        }

        const params = 'q=' + encodeURIComponent(term)
            + '&section=' + encodeURIComponent(currentSection(button));

        button.classList.add('is-processing');

        try {
            const response = await fetch(
                endpoint + '?' + params,
                {
                    headers: { 'Accept': 'application/json' },
                    credentials: 'same-origin'
                }
            );

            if (!response.ok) {
                return false;
            }

            const data = await response.json();

            if (data && !data.fallback && data.url) {
                /*
                 * Переход в текущей вкладке, а не новой: команда
                 * звучит как «открой у меня», то есть человек просит
                 * ПЕРЕЙТИ в свой интерфейс, а не добавить ещё одну
                 * вкладку поверх той, где он уже работает.
                 */
                window.location.assign(
                    contextPath(button) + data.url
                );
                return true;
            }

            /*
             * Объект найден, но раздела для него у роли нет —
             * продолжаем как обычный поиск: находку терять нельзя,
             * пользователь увидит сводку. Термин сервер вернул тем
             * же, что и присылали, поэтому нормализовать повторно
             * не нужно.
             */
            const query = (data && data.query) || term;

            field.value = query;
            field.dispatchEvent(new Event('input', { bubbles: true }));

            return true;

        } catch (error) {
            return false;
        } finally {
            button.classList.remove('is-processing');
        }
    }

    /* ============================================================
       РАСПОЗНАВАНИЕ
       ============================================================ */

    function recognitionConstructor() {
        return window.SpeechRecognition || window.webkitSpeechRecognition;
    }

    /*
     * Поле, в которое кладём распознанное.
     *
     * Кнопка лежит рядом со своим полем, поэтому поле ищется по
     * ближайшему контейнеру, а не по общему идентификатору: на
     * странице поиска поля два, и угадывать, какое из них «своё»,
     * нельзя.
     */
    function fieldOf(button) {
        const scope = button.closest('.gs, .search-page__form');
        const field = scope && scope.querySelector('input[type="search"]');

        if (field) {
            return field;
        }

        return button.parentElement
            ? button.parentElement.querySelector('input[type="search"]')
            : null;
    }

    function listen(button, field) {
        const Recognition = recognitionConstructor();

        if (!Recognition) {
            return;
        }

        const recognition = new Recognition();

        recognition.lang = 'ru-RU';
        recognition.interimResults = true;
        recognition.continuous = false;
        recognition.maxAlternatives = 1;

        /*
         * Сырая распознанная фраза целиком, без нормализации: по ней
         * решается, команда это или поиск (см. parseVoiceCommand).
         */
        let raw = '';

        button.disabled = true;
        button.classList.add('is-listening');

        /*
         * Пока идёт речь, поле заполняется текущим распознанным
         * текстом: человек видит, как его слышат, и успевает
         * остановиться, если микрофон слушает не то.
         *
         * Командную фразу в поле не кладём: в норме там должен
         * остаться поисковый запрос, а «открой ЗНП 5» в строке
         * поиска выглядело бы опечаткой, которую пользователь
         * заметил бы только после перехода.
         */
        recognition.onresult = event => {
            raw = '';

            for (let i = 0; i < event.results.length; i++) {
                raw += event.results[i][0].transcript + ' ';
            }

            raw = raw.trim();

            if (parseVoiceCommand(raw)) {
                return;
            }

            field.value = normalize(raw);

            /*
             * Событие 'input' — единственный способ передать запрос
             * штатному поиску: он слушает поле, а не этот скрипт, и
             * так голосовой ввод ничем не отличается от набранного
             * руками, включая debounce.
             */
            field.dispatchEvent(new Event('input', { bubbles: true }));
        };

        /*
         * Решение о команде принимается на завершении речи: пока
         * человек говорит, начало фразы ещё может измениться, и
         * уходить по «открой…» до того, как досказан номер, — значит
         * открыть не то.
         */
        recognition.onend = async () => {
            button.disabled = false;
            button.classList.remove('is-listening');

            const term = parseVoiceCommand(raw);

            if (!term) {
                return;
            }

            const normalized = normalize(term);

            /*
             * Сбой команды не должен съедать ввод: если сервер не
             * ответил, фразу отдаём обычному поиску.
             */
            const handled = await runCommand(button, field, normalized);

            if (!handled) {
                field.value = normalized;
                field.dispatchEvent(
                    new Event('input', { bubbles: true })
                );
            }
        };

        recognition.onerror = () => {
            button.disabled = false;
            button.classList.remove('is-listening');
        };

        recognition.start();
    }

    /* ============================================================
       ИНИЦИАЛИЗАЦИЯ
       ============================================================ */

    function initialize() {
        const Recognition = recognitionConstructor();

        /*
         * Кнопка скрыта в разметке и показывается только здесь:
         * браузеру без распознавания (Firefox) нечего обещать, а
         * неработающая кнопка хуже отсутствующей.
         */
        if (!Recognition) {
            return;
        }

        document.querySelectorAll('.vs__btn').forEach(button => {
            const field = fieldOf(button);

            if (!field) {
                return;
            }

            button.hidden = false;

            /*
             * Фрагмент с кнопкой и этим скриптом вставляется в каждый
             * раздел, поэтому на одной странице скрипт может быть
             * исполнен повторно: второй слушатель запускал бы второе
             * распознавание поверх первого. Кнопка отмечается один раз.
             */
            if (button.dataset.voiceBound) {
                return;
            }

            button.dataset.voiceBound = '1';

            /*
             * Повторное нажатие слушание не запускает: кнопка
             * заблокирована на время распознавания, и второй старт
             * оборвал бы первую сессию.
             */
            button.addEventListener('click', () => {
                listen(button, field);
            });
        });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initialize);
    } else {
        initialize();
    }
})();
