-- Роль BVK_EXECUTOR уже заведена, но модуль входного контроля
-- привязан к орг-подразделению (как цеха и склады в V2), поэтому
-- без этой записи карточки не к чему относить. Подразделение
-- входит в службу качества (SQ): входной контроль — функция
-- контроля качества поступающих комплектующих.
-- ============================================================

INSERT INTO organization_units
    (code, name, service_id, active)
VALUES
    (
        'Input Control Bureau',
        'Бюро входного контроля',
        (
            SELECT id
            FROM production_services
            WHERE code = 'SQ'
        ),
        TRUE
    );
