-- ============================================================
-- Возвраты с контроля БТК (доработка)
--
-- Контролёр БТК проводит операцию контроля и отмечает экземпляр
-- как требующий доработки: проведение со строк маршрута этого
-- экземпляра снимается, и работа возвращается цеху. Снимается
-- проведение, а не строки: план (сроки, экземпляр, исполнитель)
-- обязан остаться прежним — доработка выполняется в те же даты,
-- иначе график заказа перестал бы соответствовать обещанию
-- покупателя.
--
-- Одна строка на каждую снятую строку графика, а не одна на
-- экземпляр: подсветка переделки обязана встать у каждого
-- исполнителя по его собственной работе, и закрытие переделки
-- идёт ровно тем же проведением, что закрывает строку плана.
--
-- История сохраняется: запись живёт и после закрытия
-- (resolved_at), поэтому повторная доработка того же экземпляра
-- заводит новую строку, а прежняя остаётся в истории — кто
-- вернул, почему и когда переделали.
-- ============================================================

CREATE TABLE control_returns
(
    id             BIGINT        NOT NULL AUTO_INCREMENT,

    /*
     * Строка графика, проведение с которой снято.
     *
     * ON DELETE CASCADE: снять строку плана может только отмена
     * планирования (удаление строк графика), и висящий возврат по
     * исчезнувшей работе цеху не показать.
     */
    schedule_row_id BIGINT       NOT NULL,

    /*
     * Причина возврата, введённая контролёром БТК.
     *
     * Обязательна: экземпляр возвращается в цех уже проведённой
     * работой, и без причины исполнитель не понял бы, что именно
     * переделывать.
     */
    reason         VARCHAR(500)  NOT NULL,

    /* Этап/операция контроля, с которой экземпляр возвращён. */
    control_operation VARCHAR(255) NULL,

    /* Кто и когда вернул с контроля. */
    returned_by    BIGINT        NOT NULL,
    returned_at    DATETIME(6)   NOT NULL,

    /*
     * Переделка закрыта: строка проведена повторно.
     *
     * Пустое значение — открытая переделка, по ней цех видит
     * подсветку, а БТК — счётчик возвращённых.
     */
    resolved_at    DATETIME(6)   NULL,
    resolved_by    BIGINT        NULL,

    CONSTRAINT pk_control_returns
        PRIMARY KEY (id),

    CONSTRAINT fk_cr_schedule_row
        FOREIGN KEY (schedule_row_id)
            REFERENCES order_schedule_rows (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_cr_returned_by
        FOREIGN KEY (returned_by)
            REFERENCES app_users (id),

    CONSTRAINT fk_cr_resolved_by
        FOREIGN KEY (resolved_by)
            REFERENCES app_users (id),

    /* Открытые возвраты исполнителя — подсветка в «Мои операции». */
    INDEX idx_cr_row_open
        (schedule_row_id, resolved_at),

    /* Очередь доработки подразделения: возвраты по своим строкам. */
    INDEX idx_cr_returned
        (returned_at)

) ENGINE = InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
