-- ============================================================
-- УДАЛЁННЫЙ ВЫПУСК НЕ ДОЛЖЕН ЗАНИМАТЬ ЗАКАЗ ПОКУПАТЕЛЯ
--
-- Ограничение «один заказ покупателя — один выпуск» (V21, уточнено
-- V38) держит уникальный ключ uk_production_order_customer_root по
-- generated-колонке root_customer_order_id. Её выражение заполняло
-- значение для любой строки без родителя и с видом комплектования —
-- независимо от активности заказа.
--
-- Удаление выпуска (ProductionOrderService#delete) мягкое: оно
-- снимает active = false, а строку не трогает. Значит удалённый ЗП
-- продолжал держать в root_customer_order_id номер заказа покупателя,
-- и тот:
--   * не попадал в список свободных (findFreeCustomerOrders читает
--     existsRootByCustomerOrderId — исправлен тем же смыслом в коде);
--   * и даже после правки кода упёрся бы в уникальный ключ при
--     сохранении нового выпуска на тот же заказ покупателя.
--
-- Поэтому выражение уточняется третьим условием — только ДЕЙСТВУЮЩИЕ
-- выпуски (active = true) занимают заказ покупателя. Удалённый выпуск
-- получает NULL по служебной колонке, ключ его больше не ограничивает,
-- и заказ освобождается для нового выпуска.
--
-- Пересчёт STORED-колонки выполняет сам MODIFY: выражение меняется,
-- значения пересчитываются по всем строкам. Отдельный UPDATE не нужен
-- и невозможен (колонка GENERATED ALWAYS).
-- ============================================================

ALTER TABLE production_orders
    MODIFY COLUMN root_customer_order_id BIGINT
    GENERATED ALWAYS AS (
        IF(parent_production_order_id IS NULL
               AND znp_kind = 'KITTING'
               AND active = TRUE,
           customer_order_id,
           NULL)
    ) STORED;
