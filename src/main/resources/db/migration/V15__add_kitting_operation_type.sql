-- ============================================================
-- Новый тип операции: комплектовочная
--
-- Тип «Комплектовочная» (KITTING) используется при создании
-- заказа на производство: оператор выбирает операцию именно
-- с этим типом, после чего к ней привязывается заказ покупателя.
--
-- Тип добавляется через NOT EXISTS, чтобы миграция была
-- идемпотентной и не конфликтовала с уникальным индексом
-- uk_operation_type_code, если строка уже внесена вручную.
-- ============================================================

INSERT INTO operation_types
    (code, name, active)
SELECT
    'KITTING',
    'Комплектовочная',
    TRUE
WHERE NOT EXISTS (
    SELECT 1
    FROM operation_types
    WHERE code = 'KITTING'
);
