-- ============================================================
-- Компонент V83: тип операции "Комплектование ячеек"
-- ============================================================
-- Групповой ЗНП заводится изделием и количеством и ведётся по
-- техпроцессу, поэтому состав заказу набирает первая операция
-- маршрута, а не выбор серийников выпуска. Чтобы сервис видел,
-- ЧЕМ именно комплектуют заказ, у комплектования ячеек появился
-- отдельный код — по образцу KITTING_SUBASSEMBLY (V55), который
-- отвечает за подсборки.
--
-- Набор кодов комплектования теперь такой:
--   KITTING             — комплектовочная (заказ-комплектующий
--                         внутри выпуска, состав = серийники);
--   KITTING_CELL        — комплектование ячеек (групповой ЗНП);
--   KITTING_SUBASSEMBLY — комплектование подсборок (групповой ЗНП).
--
-- Подразделение операции решает, кто комплектует: склад
-- полуфабрикатов — обычное комплектование, бюро технического
-- контроля — ремонт ячеек или подсборок.
--
-- Строка вставляется через NOT EXISTS, чтобы миграция осталась
-- идемпотентной и не спорила с уникальным индексом
-- uk_operation_type_code, если код внесён вручную.
-- ============================================================

INSERT INTO operation_types (code, name, active)
SELECT 'KITTING_CELL', 'Комплектование ячеек', TRUE
WHERE NOT EXISTS (
    SELECT 1 FROM operation_types WHERE code = 'KITTING_CELL'
);
