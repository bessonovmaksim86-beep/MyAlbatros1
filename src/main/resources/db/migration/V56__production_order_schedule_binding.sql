-- ============================================================
-- Вторая ветвь основания строки графика: заказ на производство
--
-- order_schedule_rows (V43) планировала операции техпроцесса только
-- ПО ЗАКАЗУ ПОКУПАТЕЛЯ: order_id NOT NULL, а экземпляр задавался парой
-- «позиция + номер внутри позиции». Групповой заказ-комплектующий
-- (V38) заказа покупателя не имеет — у него свой техпроцесс (V40) и
-- своё количество, поэтому завести ему строки плана было некуда:
-- колонки основания пусты, уникальный индекс V43 требует order_id.
--
-- Следствие: операции маршрута группового ЗНП нигде не живут. Цех не
-- видит «Монтаж подсборок» в распределении и в «Мои операции», потому
-- что цех читает план, а не матрицу изделия, — и следующая после
-- комплектования операция не появляется, даже когда склад уже внёс
-- все ячейки.
--
-- РЕШЕНИЕ. Строка графика получает второе основание — заказ на
-- производство, а пара «заказ покупателя / заказ на производство»
-- обязательна ровно одной из двух (chk_osr_base_exactly_one). Позиция
-- и индекс экземпляра сохраняют смысл: для ЗНП позиция остаётся 0, а
-- индексом экземпляра служит порядковый номер изделия в заказанном
-- количестве, поэтому зависимость маршрута считается тем же ключом
-- экземпляра.
--
-- Экземпляр ЗНП с ячейкой не связывается: строки плана заводятся при
-- взятии заказа в работу, когда состав ещё не внесён складом, —
-- привязывать было бы не к чему, а колонка повисла бы пустой.
--
-- Уникальный индекс старой ветви не перестраивается: для строк ЗНП
-- order_id пуст и MySQL не считает такие строки повторяющимися, а для
-- новой ветви заведён отдельный индекс.
-- ============================================================

ALTER TABLE order_schedule_rows
    MODIFY COLUMN order_id BIGINT NULL;

ALTER TABLE order_schedule_rows
    ADD COLUMN production_order_id BIGINT NULL AFTER order_id;

ALTER TABLE order_schedule_rows
    ADD CONSTRAINT fk_osr_production_order
        FOREIGN KEY (production_order_id)
        REFERENCES production_orders (id)
        ON DELETE CASCADE;

/*
 * Ровно одно основание: строка либо планирует экземпляр позиции
 * заказа покупателя, либо операцию заказа на производство. Пустое
 * основание означало бы работу без заказчика и без срока, а два —
 * двоякий смысл при снятии плана с снятого с работы заказа.
 */
ALTER TABLE order_schedule_rows
    ADD CONSTRAINT chk_osr_base_exactly_one
        CHECK (
            (order_id IS NOT NULL AND production_order_id IS NULL)
            OR (order_id IS NULL AND production_order_id IS NOT NULL)
        );

/*
 * Та же сила, что у uk_osr_order_item_instance_operation, но для
 * ЗНП: одна операция маршрута одного экземпляра заказа один раз.
 * Позиция не участвует — у заказа на производство позиций нет.
 */
ALTER TABLE order_schedule_rows
    ADD CONSTRAINT uk_osr_prod_order_instance_operation
        UNIQUE (production_order_id, instance_index, operation_id);

/* План заказа на производство — снятие, перечитывание и счётчики. */
ALTER TABLE order_schedule_rows
    ADD INDEX idx_osr_production_order_status
        (production_order_id, status);
