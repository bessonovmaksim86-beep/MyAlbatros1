-- ============================================================
-- V96 — ВИД ЗНП «ГРУППОВОЙ НА ИЗГОТОВЛЕНИЕ ПОДСБОРОК»
--
-- Раздел «Групповые ЗНП» дополняется видом GROUP_SUBASSEMBLY. Заказ
-- заявлен изделием (типа «Ячейка») и количеством и ведётся техпроцессом,
-- как и прочие групповые виды, но номера у него появляются иначе.
--
-- У «Группового ЗНП на ячейки» состав набирает склад: кладовщик вносит
-- в матрицу комплектования уже оприходованные подсборки, и приёмка
-- переводит их в ячейки. Здесь склад ничего не подбирает — подсборки
-- выпускает цех, поэтому номера не берутся с полки, а генерируются по
-- правилу прихода (следующий свободный ряд классификатора берётся и
-- ставится в резерв в момент комплектования заказа).
--
-- CHECK вида (V37) перечисляет допустимые значения явно, поэтому
-- новое значение добавляется пересозданием ограничения: MySQL не
-- позволяет дополнить список CHECK на месте, и прежний вариант
-- отклонил бы вставку GROUP_SUBASSEMBLY.
--
-- Значение по умолчанию остаётся KITTING: старые строки и заказы
-- верхнего уровня видом не выбираются, и ничего переписывать не нужно.
-- ============================================================

ALTER TABLE production_orders
    DROP CHECK chk_production_order_znp_kind;

ALTER TABLE production_orders
    ADD CONSTRAINT chk_production_order_znp_kind
        CHECK (
            znp_kind IN (
                'KITTING',
                'GROUP_CELL',
                'GROUP_DEVICE',
                'GROUP_SUBASSEMBLY',
                'CELL_REPAIR',
                'SUBASSEMBLY_REPAIR'
            )
        );
