-- ============================================================
-- ВИДЫ ЗНП: КОМПЛЕКТОВАНИЕ, ГРУППОВЫЕ (ЯЧЕЙКИ / ПРИБОРЫ), РЕМОНТ
--
-- Диспетчер заводит заказ-комплектующий (ЗНП) не только чтобы
-- укомплектовать датчик. Ему нужны заказы:
--
--   * ЗНП на комплектование       — прежний вид (V21): составом служат
--        конкретные серийные номера родительского выпуска;
--   * групповой ЗНП на ячейки     — заказ сразу на группу ячеек одного
--        наименования, поэтому называется изделие и количество, а не
--        перечень номеров;
--   * групповой ЗНП на приборы    — тот же принцип для изделий «Прибор»;
--   * ЗНП на ремонт ячеек         — изделие типа «Ячейка» + количество;
--   * ЗНП на ремонт подсборок     — то же, различие несёт сам вид:
--        подсборка и ячейка различаются стадией движения, а не типом
--        классификатора (см. QuarantineCellKind), поэтому справочник
--        изделий у них общий.
--
-- Всё это остаётся ЗАКАЗОМ-КОМПЛЕКТУЮЩИМ внутри того же выпуска:
-- тот же номер, та же операция, то же закрытие по дереву. Поэтому
-- новая таблица не заводятся, а заводятся колонки — как это уже
-- сделано для самого уровня дерева в V21.
--
-- ЗАЧЕМ НЕ repair_orders (V34). Заказ на ремонт службы качества —
-- документ движения брака: у него нет заказчика и выпуска, зато есть
-- поставщик и перечень ячеек изолятора. Диспетчерский ЗНП на ремонт
-- заводится ВНУТРЬ выпуска (наследует заказчика и срок) и входит в
-- матрицу выпуска вместе с комплектующими. Разная природа — разные
-- таблицы; здесь ремонтом называют работу, заявленную к выпускаемому
-- изделию.
--
-- КОЛОНКИ.
--
-- znp_kind — вид заказа. Обязательна с НЕ NULL и значением по
-- умолчанию KITTING: заказы, заведённые до появления выбора, и есть
-- комплектование, других в реестре нет, и чтение старых строк не
-- должно падать.
--
-- product_classifier_id и quantity — состав «изделием и количеством»
-- для групповых и ремонтных видов. Обе колонки остаются NULL-разрешающими:
-- у комплектования состава такого нет (там перечень серийников), а
-- CHECK, обязывающий заполнить их для прочих видов, выразить над
-- другой таблицей нельзя — вид лежит здесь же, поэтому проверка
-- «вид ⇒ изделие и количество» держится сервисом.
--
-- quantity DECIMAL(15,3) — тот же тип, что у количества позиции заказа
-- покупателя (V12) и у состава классификатора (V3): количество в учёте
-- дробное, единицы измерения различаются.
-- ============================================================


-- ============================================================
-- 1. Вид ЗНП
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN znp_kind VARCHAR(30) NOT NULL DEFAULT 'KITTING'
        AFTER parent_production_order_id;

ALTER TABLE production_orders
    ADD CONSTRAINT chk_production_order_znp_kind
        CHECK (
            znp_kind IN (
                'KITTING',
                'GROUP_CELL',
                'GROUP_DEVICE',
                'CELL_REPAIR',
                'SUBASSEMBLY_REPAIR'
            )
        );

/*
 * Значение по умолчанию закрывает только ВСТАВКИ без колонки.
 * Существующие строки ALTER с DEFAULT в MySQL переписывает, но явная
 * разметка нужна, если миграцию применяют к базе, где колонку уже
 * добавляли вручную: UPDATE идемпотентен и не трогает заполненные виды.
 *
 * Вид получают только дочерние заказы: у заказа верхнего уровня (ЗП)
 * выбора вида нет, и оставлять ему «комплектование» означало бы
 * приписать выпуску несуществующий смысл. Для ЗП колонка служит
 * столько же, сколько parent_production_order_id, — то есть ничего.
 */
UPDATE production_orders
SET znp_kind = 'KITTING'
WHERE parent_production_order_id IS NOT NULL;

CREATE INDEX idx_production_order_znp_kind
    ON production_orders (znp_kind);


-- ============================================================
-- 2. Состав «изделием и количеством»
--
-- Групповой и ремонтный заказ описан одним изделием и количеством:
-- диспетчер пишет «ячейка 1212 — 24 шт.», а не перебирает номера.
-- Номера таких заказов появятся позже, по ходу выпуска, и привязывать
-- заказ к конкретным серийникам на этапе заявки не к чему.
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN product_classifier_id BIGINT NULL
        AFTER znp_kind,

    ADD COLUMN quantity DECIMAL(15, 3) NULL
        AFTER product_classifier_id;

ALTER TABLE production_orders
    ADD CONSTRAINT fk_production_order_classifier
        FOREIGN KEY (product_classifier_id)
            REFERENCES product_classifier (id);

ALTER TABLE production_orders
    ADD CONSTRAINT chk_production_order_quantity
        CHECK (quantity IS NULL OR quantity > 0);

CREATE INDEX idx_production_order_classifier
    ON production_orders (product_classifier_id);
