-- ============================================================
-- ЗАКАЗ НА РЕМОНТ: НОМЕР ВРУЧНУЮ, КОМПЛЕКТАЦИЯ И РЕМОНТ СИЛАМИ СДП
--
-- Три правки формы ЗНП, которые меняют заголовок заказа:
--
-- 1. Номер вводит руководитель службы, а не генератор: бумажный ЗНП
--    заводят по журналу подразделения, и автономер «первого свободного»
--    расходился бы с журналом. Поле остаётся необязательным — при
--    пустом значении номер по-прежнему подбирает сервис, поэтому
--    колонка не меняется, меняется только порядок её заполнения.
--
-- 2. «Ремонт с выдачей комплектации» — отметка к заказу, а не отдельный
--    вид: комплектацию выдают вместе с ремонтом ячейки или подсборки,
--    поэтому перечню компонентов место в заголовке заказа, а не в
--    справочнике видов. Перечень — свободный текст: состав компонентов
--    заказчик описывает словами, справочника комплектующих для этого
--    заказа не заводят.
--
-- 3. Ремонт могут выполнять не только поставщик, но и собственные силы
--    (СДП). Такой заказ остаётся заказом на ремонт, но вместо ссылки на
--    справочник поставщиков получает маршрут — техпроцесс, по которому
--    ремонт выполняют. Ссылка на tech_processes, а не текст: маршрут
--    выбирают из справочника, и по нему сверяют состав операций.
--
-- Существующие заказы правкой не затрагиваются: новые колонки имеют
-- значения по умолчанию, а набор order_type остаётся прежним (KITS_ISSUE
-- остаётся допустимым для ранее оформленных заказов, новые такие заказы
-- не создают — комплектация теперь отметка).
-- ============================================================


ALTER TABLE repair_orders
    ADD COLUMN kits_issue BOOLEAN       NOT NULL DEFAULT FALSE
        AFTER order_type,

    ADD COLUMN kits_list  VARCHAR(2000) NULL
        AFTER kits_issue,

    ADD COLUMN by_sdp     BOOLEAN       NOT NULL DEFAULT FALSE
        AFTER supplier_id,

    ADD COLUMN tech_process_id BIGINT   NULL
        AFTER by_sdp,

    ADD CONSTRAINT fk_repair_order_tech_process
        FOREIGN KEY (tech_process_id)
        REFERENCES tech_processes (id);

/*
 * Ремонт силами СДП без маршрута — заказ, по которому исполнитель не
 * понимает, что делать; комплектация без перечня — то же самое.
 * Ограничение держит инвариант в базе, а не только в сервисе: заказ
 * могли завести и правкой данных в обход формы.
 */
ALTER TABLE repair_orders
    ADD CONSTRAINT chk_repair_order_sdp
        CHECK (
            by_sdp = FALSE
            OR tech_process_id IS NOT NULL
        ),

    ADD CONSTRAINT chk_repair_order_kits
        CHECK (
            kits_issue = FALSE
            OR (kits_list IS NOT NULL AND TRIM(kits_list) <> '')
        );
