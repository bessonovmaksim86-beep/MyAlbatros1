-- ============================================================
-- V73 -- Журнал административных удалений
--
-- Раздел «Очистка данных» удаляет записи физически: заказ на
-- производство вместе со связанными операциями и графиком, партию
-- оприходования вместе с внесёнными номерами. Физическое удаление
-- не оставляет в самой таблице следа, поэтому факт удаления пишут
-- сюда — иначе через месяц никто не восстановит, исчезла ли запись
-- по ошибке или её удалил администратор.
--
-- target_id СОЗНАТЕЛЬНО БЕЗ ВНЕШНЕГО КЛЮЧА. Ссылка на удалённую
-- строку повисла бы, и MySQL либо отказался бы удалить запись
-- (RESTRICT по колонке аудита — абсурд: журнал блокировал бы
-- строку журнала каскадом вместе с заказом — а
-- тогда журнала как средства разбора претензий не существует.
-- Поэтому вместо ссылки хранят и идентификатор, и номер записи
-- текстом (target_label): удалённый заказ читают из журнала, не
-- обращаясь к production_orders.
--
-- affected_counts — развёртка удалённого состава («Плановые операции
-- цеха: 14; Строки графика: 6; ...»). Её держат строкой, а не
-- дочерней таблицей: строки этих групп сами удаляются, и считать их
-- post factum было бы не по чему.
-- ============================================================

CREATE TABLE admin_deletions
(
    id              BIGINT        NOT NULL AUTO_INCREMENT,

    /* PRODUCTION_ORDER — заказ (ЗП или ЗНП), RECEIVING_BATCH — партия оприходования. */
    target_kind     VARCHAR(30)   NOT NULL,

    /* Идентификатор удалённой записи; внешнего ключа нет намеренно (см. шапку). */
    target_id       BIGINT        NULL,

    /* Номер записи текстом: заказ «ЗП-2026-014», партия по приходному ордеру. */
    target_label    VARCHAR(200)  NOT NULL,

    /* HARD_DELETE — физическое удаление, RECEIVING_ROLLBACK — откат оприходования. */
    action          VARCHAR(30)   NOT NULL,

    /* Развёртка удалённого состава: «группа: число; группа: число». */
    affected_counts VARCHAR(2000) NULL,

    /* Комментарий администратора — зачем удалили. */
    note            VARCHAR(2000) NULL,

    /* Удалили из интерфейса другой роли — записывают и того, кто вошёл. */
    impersonated_by VARCHAR(255)  NULL,

    /* Учётная запись администратора; колонка аудита тоже без FK — пользователя разблокируют или удалят. */
    actor_id        BIGINT        NULL,

    /* ФИО на момент удаления: учётную запись переименовывают, журнал обязан остаться читаемым. */
    actor_name      VARCHAR(255)  NOT NULL,

    performed_at    DATETIME(6)   NOT NULL,

    CONSTRAINT pk_admin_deletions
        PRIMARY KEY (id),

    CONSTRAINT chk_admin_deletion_target_kind
        CHECK (target_kind IN ('PRODUCTION_ORDER', 'RECEIVING_BATCH')),

    CONSTRAINT chk_admin_deletion_action
        CHECK (action IN ('HARD_DELETE', 'RECEIVING_ROLLBACK')),

    /* Лента журнала: свежие удаления сверху. */
    INDEX idx_admin_deletion_performed_at
        (performed_at),

    /* «Что удаляли по этому заказу» — разбор повторных обращений. */
    INDEX idx_admin_deletion_target
        (target_kind, target_id)

) ENGINE = InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
