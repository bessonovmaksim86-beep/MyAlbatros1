-- ============================================================
-- Чистка плана по заказам покупателя, снятым с работы
--
-- ПРОБЛЕМА.
-- Заказ покупателя не стирается из базы, а снимается с работы:
-- CustomerOrderService#delete ставит status = DELETED и active = false
-- (V12 — колонка active, V13 — статус DELETED). Тот же метод снимает и
-- всё запланированное по заказу: строки графика обеих стадий и
-- плановые цеховые операции изделий.
--
-- Если заказ снят с работы иначе — напрямую в базе, или до того, как
-- эта чистка появилась в сервисе, — его план остаётся. Дальше цех
-- видит работу без основания: руководитель в «Распределении работ»
-- получает операции по заказу, которого в списках диспетчера уже нет
-- (списки отобраны по active = true), а планировщик считает эти часы
-- занятыми и отклоняет расчёт следующего заказа.
--
-- ЧТО СТИРАЕТСЯ.
-- Только намерение, никогда — событие. Признак снятого заказа один и
-- тот же во всей системе: customer_orders.active = FALSE (см.
-- CustomerOrderRepository#findAllListItems, countByActiveTrue).
--
--   1) order_schedule_rows — строки графика, ещё не проведённые
--      (completed_at IS NULL). Стадия не важна: сервис при удалении
--      снимает и DRAFT, и CONFIRMED, потому что внесённые в план часы
--      участвуют в загрузке этапов (V43) и ложно занимали бы людей.
--      Сюда же попадают строки осиротевших заказов — order_id, которого
--      в customer_orders уже нет (следствие физического удаления).
--      Проведённая строка — факт работы цеха (V44), она переживает
--      заказ ровно так же, как заказ с проведёнными строками не
--      удаляется штатно (existsCompletedScheduleRow).
--   2) product_serial_operations с пустым actual_date — план цеховых
--      операций. Заказ относится к операции двумя путями, и снимаются
--      обе ветви — те же, что у deletePlannedByCustomerOrderId и у
--      проверки перед удалением:
--        * операция поставлена в рамках заказа на производство этого
--          основания (production_order_id, V20);
--        * изделие зарезерировано позицией самого заказа покупателя
--          (product_serials.customer_order_item_id, V45).
--      Факт (actual_date) — событие, оно остаётся.
--
-- ЧЕГО ЗДЕСЬ НЕТ.
-- Резервы и реестр серийников (product_serials) не трогаются: номер —
-- не операция цеха, а запись реестра, на который смотрит склад (V42);
-- на экран распределения он не влияет, а штатное удаление заказа
-- освобождает резервы само (deleteFreeByCustomerOrderId,
-- unlinkReleasedByCustomerOrderId).
--
-- ЗАЧЕМ ЕЩЁ ФИЛЬТР В ЗАПРОСАХ.
-- Миграция разовая: она убирает то, что уже накопилось. Чтобы
-- осиротевший план не вернулся, OrderScheduleRowRepository во всех
-- цеховых запросах и запросах загрузки фильтрует строки по active
-- заказа.
-- ============================================================


-- ------------------------------------------------------------
-- 1. График заказов, снятых с работы, и осиротевшие строки графика
-- ------------------------------------------------------------

DELETE osr
FROM order_schedule_rows osr
         LEFT JOIN customer_orders co
                   ON co.id = osr.order_id
WHERE (co.id IS NULL OR co.active = FALSE)
  AND osr.completed_at IS NULL;


-- ------------------------------------------------------------
-- 2. План цеховых операций: операция в рамках заказа на производство
-- ------------------------------------------------------------

DELETE pso
FROM product_serial_operations pso
         JOIN production_orders po
              ON po.id = pso.production_order_id
         JOIN customer_orders co
              ON co.id = po.customer_order_id
WHERE pso.actual_date IS NULL
  AND co.active = FALSE;


-- ------------------------------------------------------------
-- 3. План цеховых операций: изделие зарезерировано позицией заказа
-- ------------------------------------------------------------

DELETE pso
FROM product_serial_operations pso
         JOIN product_serials ps
              ON ps.id = pso.serial_id
         JOIN customer_order_items coi
              ON coi.id = ps.customer_order_item_id
         JOIN customer_orders co
              ON co.id = coi.order_id
WHERE pso.actual_date IS NULL
  AND co.active = FALSE;