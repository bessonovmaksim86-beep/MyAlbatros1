-- ============================================================
-- ЗНП КАК ДОКУМЕНТ ДВИЖЕНИЯ: ЗАЯВКА ДИСПЕТЧЕРА → СОСТАВ СЛУЖБЫ
-- КАЧЕСТВА → ВОЗВРАТ ДИСПЕТЧЕРУ
--
-- Порядок работы меняется, и вместе с ним меняется то, ЧЕМ является
-- заказ на ремонт.
--
-- Раньше ЗНП целиком оформлял руководитель службы качества: он отмечал
-- ячейки в изоляторе, и из отмеченного состава выводились и разновидность
-- изделий, и их наименование. Теперь документ заводит диспетчер: он
-- пишет номер, выбирает тип ячеек и классификатор, а служба качества
-- только набирает состав этого типа и этого классификатора из изолятора
-- брака. После набора заявка возвращается диспетчеру, который выбирает
-- техпроцесс и ставит ЗНП в график (отдельная задача).
--
-- Отсюда три правки схемы:
--
-- 1. Тип изделий и классификатор переезжают на заголовок заказа. Пока
--    состав выводили из ячеек, держать их в заголовке было незачем. Как
--    только их назначает диспетчер ДО появления состава, они обязаны
--    храниться сами по себе: иначе заявка без состава не описывала бы
--    ничего, и служба качества не знала бы, какой именно состав набирать.
--
-- 2. Состав перестаёт быть частью оформления заявки и становится
--    наполнением уже заведённого заказа. Ограничение на однородность
--    состава в базе не заводят: соответствие ячеек типу и классификатору
--    проверяет сервис при наборе, а CHECK над набором строк другой
--    таблицы в базе всё равно не выражается.
--
-- 3. В statuses появляется возврат диспетчеру. Прежний набор описывал
--    ремонт как работу («сформирован → в работе → выполнен»), теперь же
--    документ проходит через двух исполнителей, и между ними обязана
--    быть различимая остановка: служба качества набор закончила,
--    техпроцесса ещё нет.
--
-- Заполнение существующих заказов. Состав уже лежит в
-- repair_order_items, поэтому тип и классификатор существующих заказов
-- выводят из него: у ранее оформленных заказов состав однородный
-- (сервис не пропускал смешанный), так что вывод однозначен. Заказов без
-- состава это не касается — такие строки остаются с пустыми значениями и
-- заполняются при первом наборе.
-- ============================================================


-- ============================================================
-- 1. Тип изделий и классификатор на заголовке
-- ============================================================

ALTER TABLE repair_orders
    ADD COLUMN cell_kind            VARCHAR(20) NULL AFTER order_type,
    ADD COLUMN product_classifier_id BIGINT     NULL AFTER cell_kind;

ALTER TABLE repair_orders
    ADD CONSTRAINT fk_repair_order_classifier
        FOREIGN KEY (product_classifier_id)
        REFERENCES product_classifier (id),

    ADD CONSTRAINT chk_repair_order_cell_kind
        CHECK (
            cell_kind IS NULL
            OR cell_kind IN ('SUBASSEMBLY', 'CELL')
        );

CREATE INDEX idx_repair_order_classifier
    ON repair_orders (product_classifier_id);

/*
 * Значения берут из состава: строки заказа уже однородны по
 * разновидности и изделию, поэтому достаточно первой строки. Заказ без
 * состава остаётся с NULL — его заполнит набор.
 */
UPDATE repair_orders ord
SET cell_kind = (
        SELECT item.cell_kind
        FROM repair_order_items item
        WHERE item.repair_order_id = ord.id
        ORDER BY item.position, item.id
        LIMIT 1
    ),
    product_classifier_id = (
        SELECT item.product_classifier_id
        FROM repair_order_items item
        WHERE item.repair_order_id = ord.id
          AND item.product_classifier_id IS NOT NULL
        ORDER BY item.position, item.id
        LIMIT 1
    )
WHERE cell_kind IS NULL;


-- ============================================================
-- 2. Статус возврата диспетчеру
--
-- NEW → IN_WORK (служба качества набирает состав) → RETURNED (заявка
-- вернулась диспетчеру за техпроцессом) → DONE. CANCELLED доступен с
-- любой незакрытой стадии.
-- ============================================================

ALTER TABLE repair_orders
    DROP CONSTRAINT chk_repair_order_status;

ALTER TABLE repair_orders
    ADD CONSTRAINT chk_repair_order_status
        CHECK (
            status IN ('NEW', 'IN_WORK', 'RETURNED', 'DONE', 'CANCELLED')
        );


-- ============================================================
-- 3. Техпроцесс больше не принадлежит моменту создания заявки
--
-- V35 требовала маршрут всякий раз, когда заказ ведут собственные
-- силы. Тогда заказ целиком оформлял руководитель службы качества, и
-- маршрут был известен в момент вставки строки. Теперь маршрут выбирает
-- диспетчер — уже после того, как служба качества набрала состав, то
-- есть позже вставки на неопределённое время.
--
-- Ограничение снимают, а не ослабляют условием по статусу: статус у
-- заявки меняют, и проверка «ROUTE REQUIRED, ПОКА НЕ ТОТ СТАТУС»
-- развалилась бы при первом же возврате. Обязательность маршрута
-- держит сервис при постановке заявки в график.
-- ============================================================

ALTER TABLE repair_orders
    DROP CONSTRAINT chk_repair_order_sdp;
