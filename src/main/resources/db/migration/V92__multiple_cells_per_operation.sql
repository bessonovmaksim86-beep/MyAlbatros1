-- ============================================================
-- V92: Несколько ячеек в одной операции техпроцесса
-- ============================================================
-- Технолог вправе задать в одной операции несколько строк
-- «Ячейка №», каждая со своим классификатором (ЯДВ3, ЯПР39,
-- ЯПР64, …): комплектация на приборы требует внести с полки
-- ячейки каждого вида. Раньше и сервис техпроцесса, и уникальный
-- индекс фактов считали повтором сам параметр, не глядя на
-- ячейку, — вторая строка «Ячейка №» отклонялась.

-- Факт контролируемого параметра (operation_control_params)
-- привязан к экземпляру и параметру: прежний ключ
-- uk_ocp_row_param (schedule_row_id, control_param_id) запрещал
-- вторую отметку того же параметра на одной строке графика, а
-- теперь отметок одного параметра может быть несколько — по
-- числу заданных ячеек.

-- Уникальность сохраняем на уровне тройки «строка + параметр +
-- ячейка». Номера ячеек у TEXT/LIST нет (cell_classifier_id IS
-- NULL), а в MySQL NULL в составном уникальном ключе не считается
-- равным NULL — без отдельного ключа TEXT/LIST перестал бы
-- защищаться от повтора. cell_mode_key сводит NULL к 0, как
-- group_key в uk_input_control_cell_per_group (V64): для
-- TEXT/LIST тройка вырождается в прежнюю пару «строка +
-- параметр», для ячейки различает её классификатор.
-- ============================================================

ALTER TABLE operation_control_params
    ADD COLUMN cell_mode_key BIGINT
        GENERATED ALWAYS AS (IFNULL(cell_classifier_id, 0)) STORED
        AFTER cell_classifier_id;

ALTER TABLE operation_control_params
    DROP INDEX uk_ocp_row_param,
    ADD CONSTRAINT uk_ocp_row_param_cell
        UNIQUE (schedule_row_id, control_param_id, cell_mode_key);
