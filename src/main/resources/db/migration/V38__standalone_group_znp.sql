-- ============================================================
-- ГРУППОВЫЕ И РЕМОНТНЫЕ ЗНП БЕЗ ЗАКАЗА ВЕРХНЕГО УРОВНЯ
--
-- Вид ЗНП (V37) разделил комплектующие на два порядка:
--
--   * комплектование — заказ ВНУТРЬ выпуска: он выбирает заказ
--     верхнего уровня и отмечает его серийники;
--   * групповые и ремонтные виды — самостоятельные заказы: состав
--     задан изделием и количеством, ни в чей выпуск они не
--     вписываются, родителя не имеют.
--
-- Служебная колонка root_customer_order_id (V21) держит уникальность
-- «один заказ покупателя — один выпуск» и заполняется для строк БЕЗ
-- родителя. Групповой ЗНП без родителя под это условие попадает, хотя
-- выпуском не является: второй групповой заказ того же покупателя
-- отклонялся бы как «повторный выпуск».
--
-- Выражение генерируемой колонки уточняется: значение получают только
-- строки без родителя И с видом комплектования — то есть настоящие
-- выпуски. Групповые и ремонтные ЗНП остаются с NULL и ничем не
-- ограничены, ровно как дочерние заказы.
-- ============================================================

ALTER TABLE production_orders
    MODIFY COLUMN root_customer_order_id BIGINT
    GENERATED ALWAYS AS (
        IF(parent_production_order_id IS NULL
               AND znp_kind = 'KITTING',
           customer_order_id,
           NULL)
    ) STORED;
