-- INSERT IGNORE + уникальный code: повторный прогон и уже заведённые
-- вручную позиции не конфликтуют.
-- ============================================================

CREATE TABLE IF NOT EXISTS contr_agent
(
    id   BIGINT       NOT NULL AUTO_INCREMENT,
    code INT          NOT NULL,
    name VARCHAR(255) NOT NULL,

    CONSTRAINT pk_contr_agent
        PRIMARY KEY (id),

    CONSTRAINT uk_contr_agent_code
        UNIQUE (code),

    CONSTRAINT uk_contr_agent_name
        UNIQUE (name)
) ENGINE = InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

