-- ============================================================
-- ПРИОРИТЕТ ГРУППОВОГО ЗАКАЗА
--
-- Групповой ЗНП (V37, V38) самостоятелен: заказа покупателя у него
-- нет (V40), поэтому очерёдность исполнения ему не от кого наследовать.
-- Диспетчер выбирает приоритет сам — из того же справочника
-- order_priorities (V22), что и для заказов покупателя: правила
-- запуска, загруженности, переходов и отсечки общие для всех очередей.
--
-- Дата завершения отдельной колонки не требует: due_date у заказа на
-- производство есть с V16. Для выпуска и комплектования она и дальше
-- подтягивается из заказа покупателя, а групповому заказу ставится из
-- формы — заказ без срока в график не встанет.
--
-- КОЛОНКИ.
--
-- priority_id — NULL-разрешающая по той же схеме, что и tech_process_id
-- в V40: колонка появляется над уже заведёнными заказами, у которых
-- приоритета не было, а обязательной её делает сервис
-- (ProductionOrderService#requirePriority) только для групповых видов —
-- комплектованию и выпуску приоритет не назначают.
-- ============================================================


-- ============================================================
-- 1. Приоритет заказа
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN priority_id BIGINT NULL
        AFTER tech_process_id;

ALTER TABLE production_orders
    ADD CONSTRAINT fk_production_order_priority
        FOREIGN KEY (priority_id)
            REFERENCES order_priorities (id);

CREATE INDEX idx_production_order_priority
    ON production_orders (priority_id);

/*
 * Существующие заказы переводятся в «обычный» — та же логика, что при
 * переносе приоритета заказов покупателя (V22): NULL остаётся только
 * там, где приоритет не применяется, но «обычный» для старых строк
 * честнее пустого значения: заказ и так стоял в общей очереди.
 */
UPDATE production_orders
SET priority_id = (SELECT id FROM order_priorities WHERE code = 'ORDINARY')
WHERE priority_id IS NULL;
