-- ============================================================
-- V78 -- Заполнение справочника поставщиков legacy-данными
--
-- Данные берутся из contr_agent (V77) — перенесённого списка
-- контрагентов из дампа legacy-базы. В warehouse_suppliers
-- записываются с пустым примечанием: note остаётся NULL,
-- как принято для миграционных данных.
--
-- created_at — момент применения миграции, created_by — NULL.
-- ============================================================

INSERT INTO warehouse_suppliers (name, note, created_at)
SELECT name, NULL, NOW(6)
FROM contr_agent
ORDER BY id;
