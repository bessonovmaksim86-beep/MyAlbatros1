-- ============================================================
-- V60: Тип контролируемого параметра
-- ============================================================
-- Технолог выбирает тип при создании параметра, и тип определяет,
-- как заполняют значение в операции:
--
--   LIST       — параметр со списком вариантов («Проволока»,
--                «Тип трубки»). Варианты заводят в этом же
--                справочнике, в операции их выбирают из списка.
--   TEXT_INPUT — параметр со свободным вводом («Номер ячейки»).
--                Варианты не заводят, значение вписывают текстом.
--
-- Существующие параметры — справочники с вариантами, поэтому им
-- подходит LIST: DEFAULT закрывает и перенос данных, и валидацию
-- NOT NULL на уже заполненной таблице.
-- ============================================================

ALTER TABLE control_params
    ADD COLUMN type VARCHAR(20) NOT NULL DEFAULT 'LIST'
        COMMENT 'LIST — список значений, TEXT_INPUT — поле ввода';
