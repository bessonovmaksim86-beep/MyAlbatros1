-- ============================================================
-- Полное наименование изделия в позиции заказа покупателя
--
-- Оператор вносит полное обозначение изделия так, как оно указано
-- в конструкторской документации:
--
--   Датчик уровня ультразвуковой ДУУ2М-12-1-15,00-0,15-ОМ1,5**-3
--   (поплавок титановый тип II УНКР.305446.080)
--
-- Из этой строки автоматически подбирается классификатор:
--   1) по первым словам находится род датчика (sensor_catalog.name);
--   2) остаток до первого пробела разбивается на элементы по дефису,
--      нумерация элементов — с единицы;
--   3) номера значимых элементов берутся из sensor_catalog
--      .search_parameters и сравниваются с product_name классификатора.
--
-- Колонка full_name хранит исходную строку оператора «как введено»:
-- классификатор даёт только код и род, а полное обозначение с
-- параметрами и уточнениями в скобках нигде больше не сохраняется.
--
-- Колонка NULL: старые позиции и позиции, где изделие выбрано
-- без полного обозначения, остаются без значения.
-- ============================================================

ALTER TABLE customer_order_items
    ADD COLUMN full_name VARCHAR(500) NULL
        AFTER product_classifier_id;
