-- V85 -- СТАРАЯ ДАТА ПЛАНА В ИСТОРИИ ВОЗВРАТА НА ДОРАБОТКУ
--
-- Возвращённую на доработку операцию цех проводит заново, и строка
-- графика получает новую дату плана: переделка не может оставаться под
-- датой, под которой работа уже была принята и снята. Прежняя дата при
-- этом обязана сохраниться — по ней аналитик брака видит, насколько
-- просрочена переделка и когда изделие уходило на повторный этап.
--
-- order_schedule_rows.original_planned_date для этой цели не годится:
-- там живёт дата, которую назначил планировщик, и перезаписывать её
-- возвратом означало бы потерять план диспетчера (перенос просрочек
-- сознательно оставляет её нетронутой). Поэтому старая дата кладётся в
-- саму запись возврата — одна строка на одну снятую операцию, дата
-- относится ровно к ней.
-- ============================================================

ALTER TABLE rework_returns
    ADD COLUMN previous_planned_date DATE NULL AFTER cascade_to_following;
