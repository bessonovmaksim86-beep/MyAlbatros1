-- ============================================================
-- Приостановка заказа покупателя
--
-- Диспетчер вправе временно остановить работу по заказу: статус
-- SUSPENDED введён ещё в V13, но одного статуса мало — после
-- возобновления заказ обязан вернуться туда, где стоял (в «Новый»
-- или «В работе»), а не в фиксированное состояние. Поэтому рядом
-- кладётся предыдущий статус.
--
-- КОЛОНКИ.
--   suspended_from_status — статус заказа ДО приостановки; только он
--     определяет, куда заказ вернётся при возобновлении. Пока заказ
--     не приостановлен, колонка NULL.
--   suspended_reason      — причина остановки (претензия заказчика,
--     нет комплектации, стоп по договору и т. п.); видна в карточке,
--     чтобы через месяц было понятно, почему заказ стоял.
--   suspended_at          — момент приостановки, для порядка и
--     контроля длительности простоя.
--
-- ПРИОСТАНОВКА НЕ МЕНЯЕТ active: заказ остаётся во всех списках и
-- счётчиках (они отобраны по active = true) — приостановленный заказ
-- диспетчер обязан видеть, а не терять из виду, как при удалении.
--
-- ОГРАНИЧЕНИЕ. suspended_from_status принимает только «рабочие»
-- статусы, из которых заказ реально останавливают; закрытые состояния
-- (DONE/CANCELLED/DELETED) сюда не попадают — их сервис и не пускает
-- в приостановку, ограничение лишь страхует ручные правки в БД.
-- ============================================================

ALTER TABLE customer_orders
    ADD COLUMN suspended_from_status VARCHAR(20) NULL AFTER status,
    ADD COLUMN suspended_reason      VARCHAR(500) NULL AFTER suspended_from_status,
    ADD COLUMN suspended_at          DATETIME(6)  NULL AFTER suspended_reason;

ALTER TABLE customer_orders
    ADD CONSTRAINT chk_customer_order_suspended_from
        CHECK (
            suspended_from_status IS NULL
            OR suspended_from_status IN (
                'NEW', 'IN_WORK', 'PARTIALLY_DONE', 'OVERDUED'
            )
        );
