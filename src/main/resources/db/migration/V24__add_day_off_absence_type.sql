-- ВЫХОДНЫЕ КАК ОТДЕЛЬНЫЙ ВИД ОТСУТСТВИЯ
--
-- Календарь цеха должен показывать не только отсутствия людей, но и
-- нерабочие дни: массовая отметка суббот и воскресений и перенесённые
-- праздники. V23 уже применена на рабочих базах, поэтому набор видов
-- расширяется отдельной миграцией, а не правкой прежней.
-- ============================================================

ALTER TABLE employee_absences
    DROP CHECK chk_employee_absence_type;

ALTER TABLE employee_absences
    ADD CONSTRAINT chk_employee_absence_type
        CHECK (
            absence_type IN (
                'VACATION',
                'SICK',
                'UNPAID',
                'DAY_OFF'
            )
        );
