-- ============================================================
-- V86 -- СТАРТОВЫЙ НОМЕР СЕРИИ ПО КЛАССИФИКАТОРУ
--
-- Серийные номера в пред-БД уже были выданы, и новая БД обязана
-- продолжать их ряд, а не начинать с единицы: повторный номер
-- уникальный ключ (numbering_key, serial) поймал бы уже при записи,
-- когда изделие частично выпущено. Границу задаёт администратор
-- вручную и по каждому классификатору, потому что область нумерации
-- привязана к классификатору, а у датчика — к его роду (V27).
--
-- Пустое значение означает «с единицы» — прежнее поведение выдачи,
-- поэтому ни один существующий ряд не меняет старта, пока старт не
-- введён.
--
-- Ограничение по диапазону повторяет chk_product_serial_range: старт
-- обязан попадать в пятизначную серию, иначе он никогда не будет
-- достигнут и выдача встанет.
-- ============================================================

ALTER TABLE product_classifier
    ADD COLUMN start_serial INT NULL AFTER version;

ALTER TABLE product_classifier
    ADD CONSTRAINT chk_product_classifier_start_serial
        CHECK (start_serial IS NULL OR start_serial BETWEEN 1 AND 99999);
