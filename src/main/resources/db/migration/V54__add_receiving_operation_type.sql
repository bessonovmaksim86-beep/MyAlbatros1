-- ============================================================
-- Новый тип операции: приёмка на склад
--
-- Тип «Приёмка на склад» (RECEIVING) используется для операций
-- приёмки продукции на склад (ячейки, полуфабрикаты из БВК и т.п.).
--
-- Тип добавляется через NOT EXISTS, чтобы
-- миграция была идемпотентной и не
-- конфликтовала с уникальным индексом
-- uk_operation_type_code, если строка уже внесена
-- вручную.
-- ============================================================

INSERT INTO operation_types
    (code, name, active)
SELECT
    'RECEIVING',
    'Приёмка на склад',
    TRUE
WHERE NOT EXISTS (
    SELECT 1
    FROM operation_types
    WHERE code = 'RECEIVING'
);
