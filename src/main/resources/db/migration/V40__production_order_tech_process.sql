-- ============================================================
-- ТЕХПРОЦЕСС ГРУППОВОГО ЗАКАЗА
--
-- Групповой ЗНП (V37, V38) задаётся изделием и количеством и
-- существует самостоятельно: выпуска, внутрь которого он входит, у
-- него нет. Из этого следует, чего у такого заказа быть не может:
--
--   * заказа покупателя — наследовать заказчика не от чего, а
--        «один заказ покупателя — один выпуск» (V21) блокировал бы
--        второй групповой заказ того же заказчика;
--   * комплектовочной операции — операцию выпуска заказ не выполняет,
--        он не входит в выпуск.
--
-- Работы группового заказа ведут по техпроцессу заказанного изделия:
-- диспетчер выбирает маршрут сразу при заведении заказа, как это уже
-- сделано для ремонта службы качества (V35).
--
-- КОЛОНКИ.
--
-- tech_process_id — маршрут, по которому выполняют заказ. Колонка
-- NULL-разрешающая по двум причинам:
--
--   * заказу на комплектование маршрут не назначается вовсе (его
--        операции живут у выпуска), и CHECK «маршрут обязателен для
--        групповых видов» отклонил бы корректные строки комплектования;
--   * колонка появляется над уже заведёнными групповыми заказами, у
--        которых маршрута нет — обязательной её можно делать только
--        вместе с заполнением, а заполнять нечем: выбор маршрута
--        появится вместе с формой.
--
-- Обязательность маршрута для групповых видов держит сервис
-- (ProductionOrderService#requireTechProcess), как это уже сделано для
-- изделия и количества в V37.
-- ============================================================


-- ============================================================
-- 1. Маршрут заказа
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN tech_process_id BIGINT NULL
        AFTER production_operation_id;

ALTER TABLE production_orders
    ADD CONSTRAINT fk_production_order_tech_process
        FOREIGN KEY (tech_process_id)
            REFERENCES tech_processes (id);

CREATE INDEX idx_production_order_tech_process
    ON production_orders (tech_process_id);

/*
 * Обратно — запрет маршрута там, где его быть не может.
 *
 * Комплектование ведёт выпуск, а не собственный маршрут: строка с
 * маршрутом и видом «комплектование» означала бы заказ, работы которого
 * никто не описал. Существующие строки ограничение не задевает —
 * колонка только что добавлена и пуста у всех.
 */
ALTER TABLE production_orders
    ADD CONSTRAINT chk_production_order_tech_process_kind
        CHECK (
            tech_process_id IS NULL
                OR znp_kind <> 'KITTING'
        );
