-- ============================================================
-- V61: Текстовое значение контролируемого параметра операции
-- ============================================================
-- V60 ввела тип параметра. Для TEXT_INPUT («Номер ячейки») варианта
-- в справочнике нет — исполнитель вписывает значение сам, поэтому
-- ссылке на control_param_values брать неоткуда и колонка обязана
-- стать необязательной. Значение хранят прямо в строке операции:
--
--   control_param_value_id — заполнен для LIST,
--   text_value             — заполнен для TEXT_INPUT.
--
-- Уникальность строки остаётся на значении списка: для текстовых
-- параметров control_param_value_id равен NULL, а NULL в уникальном
-- индексе MySQL не ограничивает повтор — его сторожит сервис.
-- ============================================================

ALTER TABLE tech_process_operation_control_params
    MODIFY COLUMN control_param_value_id BIGINT NULL,
    ADD COLUMN text_value VARCHAR(255) NULL
        COMMENT 'Значение параметра со свободным вводом';
