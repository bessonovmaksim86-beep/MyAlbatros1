-- ============================================================
-- Два уровня заказа на производство: ЗП и ЗНП
--
-- БИЗНЕС-УТОЧНЕНИЕ (снято предположение V20 о плоском M:N):
--
--   ЗП  — заказ на производство верхнего уровня. В него входят
--         серийники изделий (датчики, приборы, ячейки, системы).
--   ЗНП — заказ на производство, входящий ВНУТРЬ конкретного датчика
--         (например, комплектование ячейкой 333). Один и тот же ЗНП
--         может входить в несколько датчиков — отсюда связь
--         «многие ко многим» между датчиком и заказом.
--
-- То есть заказы образуют ДЕРЕВО, а не два независимых списка.
-- Новый уровень вводится колонкой parent_production_order_id:
-- родитель — ЗП, дочерний — ЗНП. Оба живут в production_orders,
-- потому что это одна сущность на разных уровнях (тот же номер,
-- та же операция, тот же статус), а не новый объект.
--
-- НОМЕР ЗНП вводит оператор вручную — колонка number это уже
-- позволяет (NOT NULL + уникальность).
--
-- ОГРАНИЧЕНИЯ СОСТАВА (по ответу бизнеса — их нет):
--   * заказ может включать датчики разных типов и классификаторов;
--   * размер группы не ограничен.
-- Поэтому CHECK на однородность состава сознательно НЕ вводится.
--
-- ЗАКРЫТИЕ ПО ДЕРЕВУ: при закрытии ЗП все входящие в него ЗНП
-- закрываются. Порядок обхода дерева — дело сервиса (рекурсивный
-- обход в CHECK выразить нельзя), здесь зафиксирована сама иерархия.
-- ============================================================


-- ============================================================
-- 1. Иерархия заказов: ЗП → ЗНП
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN parent_production_order_id BIGINT NULL
        AFTER customer_order_id;

ALTER TABLE production_orders
    ADD CONSTRAINT fk_production_order_parent
        FOREIGN KEY (parent_production_order_id)
            REFERENCES production_orders (id);

ALTER TABLE production_orders
    ADD INDEX idx_production_order_parent
        (parent_production_order_id);


-- ============================================================
-- 2. Уникальность заказа покупателя — только для ЗП верхнего уровня
--
-- Исходный uk_production_order_customer_order запрещал второму заказу
-- на производство ссылаться на тот же заказ покупателя. Это верно для
-- ЗП, но ломает групповое комплектование: один заказ покупателя
-- разбивается на несколько заказов (ЗНП), и все они законно ссылаются
-- на одного покупателя.
--
-- Снимать ограничение целиком нельзя — тогда и второй ЗП на того же
-- покупателя прошёл бы незамеченным. Поэтому уникальность сужается до
-- уровня дерева служебной генерируемой колонкой.
--
-- Приём: уникальность держит только те строки, где значение НЕ NULL.
-- Значит достаточно выдать значение лишь корневым заказам:
--
--   root_customer_order_id = customer_order_id, если родитель не
--       задан (это ЗП) → (customer_order_id) уникальна, повторный ЗП
--       отклоняется ровно как раньше;
--   root_customer_order_id = NULL, если задан родитель (это ЗНП) →
--       неограниченное число дочерних заказов на того же покупателя.
--
-- Колонка сознательно НЕ ссылается на id: выражение generated-колонки,
-- зависящее от AUTO_INCREMENT, вычислялось бы в момент вставки и
-- ставило бы результат в зависимость от порядка присвоения
-- идентификаторов. Здесь выражение зависит только от двух обычных
-- колонок.
--
-- Иначе говоря: ОДИН заказ покупателя → ОДИН ЗП → много ЗНП.
-- ============================================================

ALTER TABLE production_orders
    ADD COLUMN root_customer_order_id BIGINT
        GENERATED ALWAYS AS (
            IF(parent_production_order_id IS NULL,
               customer_order_id,
               NULL)
        ) STORED;

ALTER TABLE production_orders
    ADD CONSTRAINT uk_production_order_customer_root
        UNIQUE (root_customer_order_id);

/*
 * Убрать старый uk_production_order_customer_order просто так нельзя:
 * он одностолбцовый по customer_order_id и именно он обслуживает
 * внешний ключ fk_production_order_customer_order. Новый уникальный
 * ключ построен по ДРУГОЙ колонке (root_customer_order_id) и внешне
 * ключ не покрывает, поэтому DROP INDEX упал бы с Error 1553
 * «index needed in a foreign key constraint».
 *
 * Поэтому сначала заводится обычный индекс по customer_order_id,
 * который берёт на себя обслуживание внешнего ключа, и только после
 * этого удаляется уникальный. Лишним он не будет: поиск «заказ
 * покупателя → заказ на производство» остаётся частым (проверка
 * уникальности, выборка выпусков).
 */
ALTER TABLE production_orders
    ADD INDEX idx_production_order_customer_order
        (customer_order_id);

ALTER TABLE production_orders
    DROP INDEX uk_production_order_customer_order;


-- ============================================================
-- 3. Уточнение смысла связи serial_production_orders (создана в V20)
--
-- Строка означает: «в датчик входит заказ ЗНП». Это уровень
-- «ЗАКАЗ ↔ ЭКЗЕМПЛЯР», а не «позиция ↔ экземпляр»:
--
--   production_order_items.serial_id — позиция выпуска, то есть
--       какое изделие заказ ВЫПУСКАЕТ (появляется вместе с выпуском);
--   serial_production_orders        — чем датчик УКОМПЛЕКТОВАН,
--       то есть какие дочерние заказы в него вошли; один ЗНП
--       даёт строку на каждый датчик группы.
--
-- operation_id (V20) — комплектовочная операция, выбранная оператором
-- после номера датчика. Именно она отвечает на вопрос «в рамках какого
-- заказа и какой операцией выполнена операция по датчику», поэтому
-- колонка production_order_id в product_serial_operations (V20)
-- обязательна для операций комплектования.
-- ============================================================

ALTER TABLE serial_production_orders
    COMMENT = 'Датчик ⇄ заказ на производство (ЗНП): чем укомплектован экземпляр';
