-- V95 — ОТМЕНА ПАРТИИ ПРИХОДА (СТАТУС «УДАЛЕНА»)
--
-- Кладовщик оформляет приход, и под него сразу резервируется
-- непрерывный диапазон номеров. Если партия оказалась ошибочной
-- (не тот поставщик, не то количество, приход отменён), номера
-- оставались занятыми навсегда: черновик висел в списке, а ряд
-- классификатора больше не отдавал этот промежуток ни новой партии,
-- ни заказу на производство.
--
-- Поэтому удаление — отметка, а не DELETE: реквизиты прихода
-- остаются в базе для сверки, но резерв снимается. Номера в реестр
-- такие партии не приносили (подтверждения сканированием не было),
-- поэтому освобождать больше нечего — достаточно исключить
-- зарезервированный диапазон из расчёта следующего номера.
--
-- Оприходованные партии удалению не подлежат: их номера уже в
-- product_serials и могли уйти на входной контроль или в сборку.
-- Проверка живёт в CellReceivingService#delete.
-- ============================================================

ALTER TABLE cell_receiving_batches
    ADD COLUMN deleted TINYINT(1) NOT NULL DEFAULT 0
        AFTER note;

/*
 * Счётчики незакрытых приходов и расчёт следующего номера читают
 * партии по классификатору; индекс по флагу удаляет строки отменённых
 * партий из этих выборок без полного сканирования таблицы.
 */
ALTER TABLE cell_receiving_batches
    ADD INDEX idx_cell_receiving_deleted
        (deleted, cell_classifier_id);
