-- БЮРО ТЕХНИЧЕСКОГО КОНТРОЛЯ: ОДНА ЗАПИСЬ С ПРАВЫМ ИМЕНЕМ
--
-- В начальных данных (V2) подразделение техконтроля вставлялось дважды
-- под одним кодом TECHNICAL_CONTROL_DEPARTMENT: как «Отдел технического
-- контроля» и как «Бюро технического контроля». Колонка code уникальна
-- (uk_organization_unit_code), поэтому второй вставляемый вариант —
-- ошибка, а не дубль: с нуля V2 на этом месте прерывалась, и в базе
-- оставался только «Отдел».
--
-- Здесь исправляется то, что уже лежит в рабочих базах: строку оставляют
-- и переименовывают. Удалять её нельзя — на неё ссылаются учётные записи
-- (app_users.organization_unit_id) и операции (operations.organization_unit_id),
-- а предписанные ключи такое удаление не переживут.
--
-- Условие по имени, а не по коду: код у обеих строк один, и переименовывать
-- нужно только «Отдел». Если в базе уже лежит «Бюро», запрос не делает
-- ничего — миграция обязана быть повторяемой.
-- ============================================================

UPDATE organization_units
SET name = 'Бюро технического контроля'
WHERE code = 'TECHNICAL_CONTROL_DEPARTMENT'
  AND name = 'Отдел технического контроля';
