package ru.company.production.repository;

/**
 * Строка «изделие — его техпроцесс» для списка классификатора.
 *
 * Проектная строка (Spring Data читает по алиасам), а не сущность:
 * странице классификатора нужны только код маршрута, признак
 * базовости и число операций. Тянуть целиком TechProcess означало бы
 * загрузить операции всех маршрутов сразу для сотен изделий списка.
 *
 * Строки отдают только активные маршруты: неактивный техпроцесс
 * изделием не выпускают, и показывать его в списке нельзя.
 */
public interface ClassifierRouteLinkView {

    /** Идентификатор изделия, к которому применён маршрут. */
    Long getClassifierId();

    /** Идентификатор техпроцесса. */
    Long getProcessId();

    /** Код техпроцесса. */
    String getCode();

    /** Базовый ли это маршрут для изделия. */
    boolean isBasic();

    /** Число операций маршрута. */
    long getOperationCount();
}
