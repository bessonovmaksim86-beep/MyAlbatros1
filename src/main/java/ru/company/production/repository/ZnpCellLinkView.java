package ru.company.production.repository;

/**
 * Проекция «ячейка, привязанная к заказу-комплектующему».
 *
 * Раздел комплектования ЗНП читает ею состав заказа по НОМЕРУ заказа:
 * интерфейс разрезан «изделие → операции», и у строки есть только
 * номер ЗНП, напечатанный карточкой операции. Идти от номера к
 * идентификатору заказа, а затем к его составу было бы два обращения
 * к базе там, где достаточно одного.
 *
 * Номер печатается строкой, а не парой «код + серия»: сборка
 * `код * 100000 + серия` уже живёт в {@code ProductSerialRepository},
 * и второй её пересказ в сервисе разошёлся бы с первым при смене
 * длины серии.
 *
 * В выборку попадают только ячейки ({@code productType = CELL}):
 * строка той же матрицы может связывать заказ и с датчиком, в который
 * он вошёл, а датчик — главная строка той же таблицы, и печатать его
 * составом значило бы показать изделие частью его самого.
 *
 * Spring Data проецирует алиасы JPQL на геттеры по имени, отдельная
 * реализация не нужна.
 */
public interface ZnpCellLinkView {

    String getZnpNumber();

    Long getSerialId();

    String getCellNumber();
}
