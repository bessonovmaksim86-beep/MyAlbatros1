package ru.company.production.repository;


/**
 * Незакрытая строка графика в минимальной проекции.
 *
 * Нужна для проверки зависимостей: чтобы понять, можно ли проводить
 * операцию, сравниваются пары «техпроцесс + операция» и номера заказов,
 * поэтому тащить сущности строк с исполнителями и рабочими местами
 * незачем — проекция читает ровно нужные колонки.
 *
 * Номера заказов возвращаются строкой: одна и та же зависимость
 * встречается в нескольких заказах, и именно номер решает, относится
 * незакрытая строка к этому изделию или к чужому.
 */
public interface OpenInstanceRowView {

    Long getTechProcessId();

    Long getOperationId();

    String getOrderNumber();

    /*
     * Ветвь основания строки: «CO» — заказ покупателя, «PO» — заказ на
     * производство (V56).
     *
     * В ключ экземпляра номер основания входит вместе с признаком
     * ветви: номера обоих реестров заводятся независимо и могут
     * совпасть («666» бывает и заказом покупателя, и групповым ЗНП), а
     * без признака две несвязанные работы блокировали бы друг друга.
     */
    String getBaseKind();

    Integer getItemPosition();

    Integer getInstanceIndex();

    /** Дата факта: пусто — строка ещё не проведена. */
    java.time.LocalDateTime getCompletedAt();
}
