package ru.company.production.dto;

import ru.company.production.entity.ProductionOrder;

/**
 * Строка списка «Приёмка ячеек»: заказ-комплектующий плюс признак
 * того, что приёмку уже можно провести, и подписи изделия.
 *
 * Заказ остаётся в списке всегда: кладовщик обязан видеть, что ЗНП
 * ждёт своей очереди, иначе он искал бы пропавший заказ вслепую.
 * Разделляет эти два смысла {@code acceptanceAvailable}:
 *
 *   * {@code true}  — операция приёмки дошла до своего шага, кнопка
 *       «Принять на склад» активна, заказ считает счётчик меню;
 *   * {@code false} — приёмка ещё не на очереди (план заказа не
 *       дошёл до операции либо операции нет в техпроцессе): строка
 *       есть, кнопки нет, счётчик заказ молчит.
 *
 * Заказ передаётся сущностью, а не набором строк: список печатает
 * собственные поля заказа (номер, вид, даты, статус), и все
 * они читаются запросом {@code findPendingCellZnp} — отдельная
 * проекция здесь только множил бы код.
 *
 * Изделие и его тип вынесены в отдельные строки по той же причине,
 * что и в прочих списках: связь классификатора ленивая, а открыт ли
 * список в транзакции — вопрос времени отклика страницы. Сервис
 * читает подписи внутри своего {@code @Transactional} метода и
 * отдаёт шаблону готовый текст, поэтому кладовщик видит, какие именно
 * ячейки или подсборки ждёт заказ, а не только его номер.
 */
public record ZnpAcceptanceRow(
        ProductionOrder order,
        boolean acceptanceAvailable,
        String productLabel,
        String productTypeLabel
) {
}
