package ru.company.production.dto;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Насколько опасно то, что раздел нашёл в связанном составе записи.
 *
 * Разделение на три уровня нужно не для цвета, а для поведения кнопки
 * удаления: {@link #BLOCKING} выключает её вовсе (удалять нельзя ни
 * при каком подтверждении), {@link #ATTENTION} оставляет удаление, но
 * обязывает администратора подтвердить его отдельной отметкой, а
 * {@link #INFO} просто объясняет последствия.
 *
 * Сводить всё к булеву «можно/нельзя» нельзя: «по заказу проведены
 * фактические работы цеха» и «этикетки партии уже напечатаны» — оба
 * случая удалимы руками администратора, но требуют разного
 * подтверждения, и один флаг различил бы их только текстом.
 */
@Getter
@RequiredArgsConstructor
public enum DeletionWarningLevel {

    /** Последствие, которое стоит знать, но не оно останавливает. */
    INFO("info"),

    /** Удаление сотрёт то, что создавала другая роль: нужна отметка согласия. */
    ATTENTION("attention"),

    /** Удалять нельзя: запись задействована так, что удаление порвало бы связь. */
    BLOCKING("blocking");

    /** Имя CSS-модификатора: шаблон не держит соответствие «уровень → цвет». */
    private final String badgeClass;
}
