package ru.company.production.dto;

import java.util.List;

/**
 * Группа ролей в боковом меню администратора: все роли, чей интерфейс
 * принадлежит одному модулю.
 *
 * Меню группируется по модулю, а не печатает сплошной список ролей: роли
 * цехов отличаются только подразделением, и в перечне из четырнадцати строк
 * администратору было бы сложнее найти нужный интерфейс, чем в нескольких
 * подписанных группах.
 *
 * @param title   название модуля, интерфейс которого открывают роли группы
 * @param entries роли группы в порядке справочника
 */
public record RoleMenuSection(
        String title,
        List<RoleMenuEntry> entries
) {
}
