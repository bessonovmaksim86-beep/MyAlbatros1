package ru.company.production.dto;

/**
 * Роль в боковом меню администратора.
 *
 * В меню администратор выбирает не учётную запись, а роль: вход всё равно
 * выполняется под конкретного сотрудника (иначе модуль не смог бы определить
 * границы своего цеха или отдела), поэтому здесь живёт заранее выбранный
 * представитель роли, а не весь список сотрудников — он остаётся в
 * {@link RoleAccessView} на странице «Роли и вход».
 *
 * @param role            код роли (имя перечисления)
 * @param displayName     человекочитаемое название роли
 * @param userId          идентификатор учётной записи для {@code /admin/switch}
 *                        либо {@code null}, если входить не под кого
 * @param userName        ФИО сотрудника, под который выполнится вход —
 *                        администратор должен видеть это до нажатия
 * @param userCount       число действующих учётных записей этой роли
 */
public record RoleMenuEntry(
        String role,
        String displayName,
        Long userId,
        String userName,
        long userCount
) {

    /**
     * Пункт меню кликабелен только при наличии действующей учётной записи:
     * вход «в пустую роль» не выполним, и показывать такую роль активной
     * значит обещать действие, которое завершится ошибкой.
     */
    public boolean canEnter() {
        return userId != null;
    }
}
