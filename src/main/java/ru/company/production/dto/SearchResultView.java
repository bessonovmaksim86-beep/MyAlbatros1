package ru.company.production.dto;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Строка результатов глобального поиска.
 *
 * Каждый результат несёт категорию, заголовок, уточняющую подпись и
 * два адреса: общий (сводка по объекту в едином интерфейсе) и адрес
 * карточки в том разделе, где объект ведут.
 *
 * Разделение адресов сознательное: поиск один на всю систему, а
 * интерфейсы разделов разные, и переход прямо в чужую страницу
 * сбивал пользователя с толку. Теперь поиск всегда ведёт в общую
 * сводку, а в раздел человек уходит сам — по кнопке сводки.
 */
@Getter
@AllArgsConstructor
public class SearchResultView {

    /**
     * Идентификатор найденной записи. Нужен общему интерфейсу
     * (category + id), чтобы прочитать объект и показать его сводку.
     */
    private final Long id;

    /**
     * Служебный ключ категории: techprocess, classifier, operation,
     * workplace, customerorder, productionorder. Нужен клиенту для
     * группировки, а общему интерфейсу — для выбора, что читать.
     */
    private final String category;

    /**
     * Человекочитаемое имя категории для заголовка группы.
     */
    private final String categoryLabel;

    /**
     * Основное наименование результата.
     */
    private final String title;

    /**
     * Уточнение: код изделия, тип, род датчика и т. п.
     */
    private final String subtitle;

    /**
     * Адрес общей сводки по объекту — туда ведёт строка выдачи.
     */
    private final String url;

    /**
     * Адрес карточки объекта в его разделе: кнопка «Открыть в
     * разделе» внутри сводки.
     */
    private final String moduleUrl;
}