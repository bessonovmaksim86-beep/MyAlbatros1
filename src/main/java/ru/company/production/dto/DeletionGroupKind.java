package ru.company.production.dto;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Что именно входит в состав записи, которую администратор снимает с
 * работы, и как это удаляется.
 *
 * Каждому элементу соответствует чекбокс на экране предпросмотра:
 * пользователь просил, чтобы при удалении компонента система либо
 * забирала всё связанное целиком, либо давала выбрать состав — этот
 * перечень и есть то, что предлагается выбрать.
 *
 * Ключи общие для заказа и партии оприходования намеренно: экран
 * предпросмотра, разбор формы и журнал удалений работают с одним
 * перечнем, и новый тип удаляемой записи получил бы свой экран лишь
 * затем, чтобы повторить тот же список чекбоксов.
 *
 * {@code mandatory} — группа, которую нельзя выключить: без её
 * удаления удаление самой записи упрётся во внешний ключ с RESTRICT,
 * и транзакция откатится на середине. Такой чекбокс показан
 * отмеченным и неактивным, чтобы отказ не выглядел сбоем.
 */
@Getter
@RequiredArgsConstructor
public enum DeletionGroupKind {

    /* ==================== Заказ на производство ==================== */

    /**
     * Вложенные заказы-комплектующие.
     *
     * Обязательны: {@code parent_production_order_id} ссылается на
     * удаляемый выпуск с RESTRICT, и оставленный ЗНП либо удержал бы
     * выпуск от удаления, либо повис бы со ссылкой на несуществующий
     * заказ.
     */
    NESTED_ZNP(
            "Вложенные заказы-комплектующие",
            "ЗНП, входящие в выпуск: они удаляются вместе с ним",
            true
    ),

    /**
     * Позиции выпуска ({@code production_order_items}).
     *
     * Обязательны: ключ заказа в этой таблице стоит с ON DELETE
     * CASCADE, строки уйдут в любом случае — перечень показывает это,
     * а не предлагает выбор.
     */
    ORDER_ITEMS(
            "Позиции выпуска",
            "Строки выпускаемых изделий заказа (каскадное удаление)",
            true
    ),

    /** Серийные номера, выданные выпуском ({@code product_serials}). */
    RELEASE_SERIALS(
            "Серийные номера выпуска",
            "Номера из реестра, выданные этим заказом; ряд нумерации освобождается",
            false
    ),

    /** Строки графика цеха ({@code order_schedule_rows}). */
    SCHEDULE_ROWS(
            "Строки графика работ",
            "Запланированные строки графика цеха и распределения работ",
            false
    ),

    /** Операции по изделиям в рамках заказа без факта. */
    PLANNED_OPERATIONS(
            "Плановые операции по изделиям",
            "Строки маршрута без фактической даты — намерение, а не работа",
            false
    ),

    /**
     * Операции по изделиям, проведённые фактом.
     *
     * Отдельная группа, а не часть плановых: это уже отметка о
     * выполненной работе цеха, и её удаление — событие, которое
     * администратор обязан подтвердить осознанно.
     */
    PERFORMED_OPERATIONS(
            "Проведённые операции по изделиям",
            "Строки маршрута с фактической датой: отметки о выполненной работе",
            false
    ),

    /** Матрица комплектования ({@code serial_production_orders}). */
    KITTING_LINKS(
            "Состав комплектования",
            "Связи «изделие ⇄ заказ»: по ним склад видит внесённые ячейки",
            true
    ),

    /** Позиции комплектования ремонтного ЗНП ({@code repair_kitting_items}). */
    REPAIR_KITTING_ITEMS(
            "Позиции комплектования ремонта",
            "Перечень номеров, внесённых в ремонтный заказ бюро входного контроля",
            false
    ),

    /* ============ Общие группы заказа и партии оприходования ============ */

    /**
     * Отметки журнала перемещений ({@code serial_movement_events}).
     *
     * Обязательны там, где удаляется номер или партия: ключ журнала
     * стоит с RESTRICT, и строки переживают удаляемую запись только
     * когда сама запись остаётся.
     */
    MOVEMENT_JOURNAL(
            "Журнал перемещений",
            "Строки истории номеров: паспорт изделия потеряет эти события",
            true
    ),

    /* ==================== Партия оприходования ==================== */

    /** Номера, внесённые приходом в реестр. */
    BATCH_SERIALS(
            "Номера, внесённые приходом",
            "Ячейки партии в реестре серийных номеров; ряд нумерации освобождается",
            false
    ),

    /** Карточки входного контроля партии и их состав. */
    INPUT_CONTROL_CARDS(
            "Карточки входного контроля",
            "Карточки БВК по партии вместе с перечнем ячеек и причинами брака",
            false
    ),

    /** Перемещения ячеек из изолятора, оформленные на эту партию. */
    QUARANTINE_TRANSFERS(
            "Перемещения из изолятора",
            "Строки передачи ячеек партии на склад: изолятор потеряет эти отметки",
            false
    ),

    /**
     * Шапка партии ({@code cell_receiving_batches}).
     *
     * Единственная группа по умолчанию снятая: откат оприходования
     * оставляет приход черновиком, чтобы партию можно было провести
     * заново, и удаляют шапку только когда приход оформлен неверно
     * целиком.
     */
    BATCH_HEADER(
            "Сама партия прихода",
            "Заявка прихода: без неё приход исчезает совсем, а не становится черновиком",
            false
    );

    /** Заголовок группы на экране предпросмотра. */
    private final String title;

    /** Что уходит вместе с группой — подпись под заголовком. */
    private final String description;

    /** Нельзя выключить: иначе удаление упрётся во внешний ключ. */
    private final boolean mandatory;

    /**
     * Отмечена ли группа при первом показе предпросмотра.
     *
     * Снята только шапка прихода: откат оприходования по смыслу
     * оставляет партию черновиком, и отмеченная по умолчанию группа
     * «удалить совсем» превратила бы штатный откат в потерю прихода.
     */
    public boolean isDefaultSelected() {
        return this != BATCH_HEADER;
    }
}
