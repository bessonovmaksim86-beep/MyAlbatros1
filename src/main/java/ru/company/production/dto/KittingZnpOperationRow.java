package ru.company.production.dto;

import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Одна операция комплектования внутри раскрытой строки изделия.
 *
 * Раздел «Комплектование ЗНП» показывает работу разрезом «изделие →
 * его операции»: главная строка таблицы — серийный номер, а раскрытие
 * перечисляет операции этого изделия, под которые заведён заказ-
 * комплектующий (ЗНП) в статусе «в работе». Карточка операции держит
 * ровно те подписи, что просит кладовщик: наименование операции, номер
 * привязанного ЗНП, дата плана и возможность провести.
 *
 * Проводится конкретная строка графика, поэтому карточка несёт
 * {@code rowId} — ключ существующего {@code POST /warehouse/kitting/
 * complete}; отдельного write-пути раздел не заводит.
 *
 * Поле {@code attachedCellNumbers} показывает, какие серийные номера
 * (ячейки) уже вошли в этот заказ-комплектующий: кладовщик видит,
 * что уже укомплектовано, и сверяет состав до проведения операции.
 *
 * Поле {@code expectedCellTypes} содержит наименования ячеек, которые
 * операция вправе принять: их сервис находит в классификаторе по
 * обозначению из наименования операции («Комплектование ЯПР20» →
 * «ЯПР20М», «ЯПР20МД»). Пустой список означает, что наименование
 * операции ячейку не называет и подбирать её не из чего — тогда
 * состав заказа не ограничен видом изделия.
 *
 * Поле {@code cellDesignation} хранит само обозначение («ЯПР20») либо
 * пустую строку. Оно отвечает на вопрос «вообще ли эта операция собирает
 * ячейку», и только оно решает, показывать ли поле ввода: операция
 * «Комплектование поплавков для датчика» ячейку не называет, и поле
 * «Ячейка: 9 цифр» предлагало кладовщику вносить то, что в заказ не
 * входит.
 *
 * @param rowId          строка графика — ключ проведения
 * @param operationName  наименование операции («Комплектование»)
 * @param znpNumber      номер привязанного ЗНП (заказ в работе)
 * @param plannedDate    дата плана этой операции
 * @param completed      операция уже проведена
 * @param completedLabel дата проведения для подписи
 * @param blocked        есть незакрытая предшествующая по маршруту
 * @param blockerLabel   наименование блокирующей операции
 * @param canComplete    провести можно сейчас (не закрыта, не ждёт)
 * @param attachedCellNumbers серийные номера ячеек, вошедших в ЗНП
 * @param expectedCellTypes наименования ячеек, допускаемых операцией
 * @param cellDesignation обозначение ячейки из наименования операции
 */
public record KittingZnpOperationRow(
        Long rowId,
        String operationName,
        String znpNumber,
        LocalDate plannedDate,
        boolean completed,
        String completedLabel,
        boolean blocked,
        String blockerLabel,
        boolean canComplete,
        List<String> attachedCellNumbers,
        List<String> expectedCellTypes,
        String cellDesignation
) {

    /**
     * Право провести работу с учётом состава заказа.
     *
     * Сервис считает право по графику и маршруту (строка не закрыта и
     * не ждёт предшественника), а здесь к нему добавляется состав:
     * операция, называющая ячейку, не может быть закрыта, пока в
     * заказ-комплектующий не вошёл хоть один номер. Кнопка «Провести
     * операцию» и бейдж «можно провести» в шапке изделия читают этот
     * метод, поэтому правило живёт в одном месте и не расходится между
     * двумя подписями одной строки.
     *
     * Состав требуется только там, где он вообще существует: у работы
     * без заказ-комплектующего вносить номер не в состав чего, и
     * требовать его было бы условием, которое кладовщик не умеет
     * выполнить вовсе. Такая работа закрывается одним фактом.
     */
    @Override
    public boolean canComplete() {
        return canComplete && !awaitComposition();
    }

    private static final DateTimeFormatter RU_DATE =
            DateTimeFormatter.ofPattern("dd.MM.yyyy");

    /** Наименование операции — подпись колонки. */
    public String title() {
        return operationName == null || operationName.isBlank()
                ? "операция"
                : operationName.trim();
    }

    /** Номер ЗНП отдельной подписью; пустое значение — прочерк. */
    public String znpLabel() {
        return znpNumber == null || znpNumber.isBlank()
                ? "—"
                : znpNumber.trim();
    }

    /** Дата плана в привычном формате — диалект java8time не подключён. */
    public String formattedDate() {
        return plannedDate == null ? "—" : plannedDate.format(RU_DATE);
    }

    /**
     * Подпись причины блокировки: «ждёт: Сборка узла». Проведённая
     * операция блокироваться не может, поэтому для неё — прочерк.
     */
    public String blockedLabel() {
        if (!blocked) {
            return "—";
        }

        return blockerLabel == null || blockerLabel.isBlank()
                ? "ждёт предшественника"
                : "ждёт: " + blockerLabel.trim();
    }

    /**
     * Сколько ячеек уже вошло в заказ-комплектующий.
     *
     * Кладовщик видит это число, чтобы сверить состав ЗНП до
     * проведения: если операция закрыта фактом, но ячеек в составе
     * нет — значит, ЗНП был поднят вручную, без реестра.
     */
    public long attachedCount() {
        return attachedCellNumbers == null ? 0L : attachedCellNumbers.size();
    }

    /**
     * Подпись ячеек: «Ячеек вошло: 3».
     *
     * Пустое значение — прочерк, если ячеек не было или их не
     * удалось прочитать: шаблон должен показывать прочерк, а не
     * нуль, чтобы кладовщик не счёл это ошибкой.
     */
    public String attachedLabel() {
        long count = attachedCount();
        return count > 0 ? "Ячеек вошло: " + count : "—";
    }

    /**
     * Называет ли операция ячейку.
     *
     * Знак для разметки и для проверки проведения: поле ввода и
     * требование состава имеют смысл только там, где операция собирает
     * ячейку. Операция «Комплектование поплавков для датчика» ячейку не
     * называет — у неё нет ни поля ввода, ни обязанности вносить состав.
     */
    public boolean namesCell() {
        return cellDesignation != null && !cellDesignation.isBlank();
    }

    /**
     * Работа ждёт внесения состава.
     *
     * Знак для колонки статуса: без него строка показывала бы «В
     * работе» и при этом не имела кнопки проведения — кладовщик читал
     * бы это как сбой интерфейса. Подпись «ждёт состав» объясняет, что
     * закрытию мешает пустой состав заказ-комплектующего.
     *
     * Требование держится тремя признаками сразу: операция обязана
     * называть ячейку, под неё обязан быть поднят заказ (вносить номер
     * иначе некуда) и состав обязан быть пуст.
     */
    public boolean awaitComposition() {
        return !completed
                && !blocked
                && namesCell()
                && hasZnp()
                && attachedCount() == 0;
    }

    /** Под эту работу поднят заказ-комплектующий. */
    public boolean hasZnp() {
        return znpNumber != null && !znpNumber.isBlank();
    }

    /**
     * Можно ли вписать в этот заказ ещё одну ячейку.
     *
     * Заказ обязан быть живым и не закрытым фактом: внесённая после
     * проведения ячейка означала бы, что склад доукомплектовал уже
     * сданную работу, — и спор о составе остался бы неразрешимым.
     * Потолок состава (заказанное количество) проверяет сервис, а не
     * разметка: цифра состава ему известна точнее, потому что она
     * читается из графика вместе с заказом.
     *
     * Операция обязана называть ячейку: {@code namesCell()} отсекает
     * работы, где вносить нечего, — кладовщику не показывается поле,
     * заполнив которое он не улучшил бы состав заказа.
     */
    public boolean canAttachCell() {
        return !completed && namesCell() && hasZnp();
    }

    /**
     * Сколько типов ячеек допускает операция.
     *
     * Ноль — операция не называет тип ячейки, и сервис не будет
     * проверять вид изделия при привязке.
     */
    public long expectedCellTypesCount() {
        return expectedCellTypes == null ? 0L : expectedCellTypes.size();
    }

    /**
     * Подпись ожидаемых типов: «Допускаются: ЯПР20М, ЯПР20МД».
     *
     * Показывается в раскрытии под полем ввода — кладовщик видит,
     * какие ячейки можно внести, ещё до нажатия «Внести».
     */
    public String expectedCellTypesLabel() {
        if (expectedCellTypes == null || expectedCellTypes.isEmpty()) {
            return "—";
        }

        return "Допускаются: "
                + String.join(", ", expectedCellTypes);
    }
}
