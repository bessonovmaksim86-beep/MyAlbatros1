package ru.company.production.dto;

import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Данные приёмки на склад заказ-комплектующего (ЗНП).
 *
 * Номера передаются текстом, а не списком идентификаторов: кладовщик
 * вводит их с этикетки или сканера, и поле остаётся полем ввода.
 * Разбор и сверка с заказом — задача сервиса, которому известны
 * непринятые ячейки ЗНП.
 *
 * Отметка «отметить все» подставляет полный перечень ячеек заказа
 * (все его непринятые ячейки), а не пустой список.
 */
@Getter
@Setter
@NoArgsConstructor
public class ZnpAcceptanceForm {

    /** Принимаемые номера ячеек: по одному в строке. */
    @Size(max = 20000, message = "Список номеров слишком длинный")
    private String cellNumbersText;

    /**
     * Отметка «отметить все номера ячеек».
     *
     * Работает как в БВК: перечень подставляется сервером полный
     * (все непринятые ячейки заказа), а поле ввода на экране
     * закрывается от правки.
     */
    private boolean allCells;
}
