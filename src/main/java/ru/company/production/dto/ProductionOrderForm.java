package ru.company.production.dto;

import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.format.annotation.DateTimeFormat;
import ru.company.production.entity.ZnpKind;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;

/**
 * Форма создания заказа на производство.
 *
 * Состав выпуска не редактируется вручную: он выводится из позиций
 * выбранного заказа покупателя — сколько экземпляров заявлено
 * в позиции, столько строк выпуска появится, и каждая получит
 * собственный серийный номер.
 *
 * Поэтому форма держит только привязки (заказ покупателя и
 * комплектовочная операция), сроки и статус.
 */
@Getter
@Setter
@NoArgsConstructor
public class ProductionOrderForm {

    private static final DateTimeFormatter DATE_FORMATTER =
            DateTimeFormatter.ofPattern("dd.MM.yyyy");

    private Long id;

    @Size(max = 50, message = "Не более 50 символов")
    private String number;

    /**
     * Номера ЗНП по каждому серийнику выпуска.
     *
     * Выравнен по индексу с releaseSerialIds: элемент с тем же
     * номером — ручной номер ЗНП для соответствующего
     * зарезервированного серийника.
     */
    private List<String> releaseZnpNumbers = new ArrayList<>();

    /*
     * Обязательность поля проверяется сервисом, а не аннотацией:
     * заказу-комплектующему заказ покупателя не выбирается — он
     * наследуется от родительского выпуска (см. parentProductionOrderId).
     * Аннотация @NotNull отклоняла бы корректную форму ЗНП ещё до
     * обращения к сервису.
     */
    private Long customerOrderId;

    /*
     * Родительский заказ на производство (миграция V21).
     *
     * Пусто → создаётся ЗАКАЗ НА ПРОИЗВОДСТВО (ЗП): в него входят
     * серийники выпускаемых изделий, состав строится из позиций
     * заказа покупателя.
     *
     * Заполнено → создаётся ЗАКАЗ НА ПРОИЗВОДСТВО-КОМПЛЕКТУЮЩИЙ (ЗНП):
     * он входит внутрь конкретного датчика, поэтому серийники ему
     * не выдаются — составом ЗНП являются сами датчики, которые
     * подключаются отдельно.
     */
    private Long parentProductionOrderId;

    /*
     * Тип заказа, выбранный диспетчером: выпуск (ЗП) или
     * заказ-комплектующий (ЗНП).
     *
     * Уровень заказа в базе определяется родителем
     * (parent_production_order_id), но в форме выбор сделан явным
     * переключателем: вид ЗНП нужен сразу при создании комплектующего,
     * а не после того, как в списке родителей найден и выбран выпуск.
     * Переключатель лишь показывает нужные поля, сервис уровень по нему
     * не определяет — только по родителю.
     *
     * Имена значений совпадают с константами скрипта формы и читаются
     * шаблоном через isComponentLevel().
     */
    private String orderLevel = ProductionOrderForm.LEVEL_ROOT;

    public static final String LEVEL_ROOT = "ROOT";
    public static final String LEVEL_COMPONENT = "COMPONENT";

    /*
     * Вид заказа-комплектующего (миграция V37).
     *
     * Приходит ИМЕНЕМ, а не перечислением: селектор формы отдаёт строку,
     * а конвертация в enum при неверном значении отклонила бы всю форму
     * до обращения к сервису — сервис в этом случае дал бы понятное
     * сообщение, и трактует пустое значение как комплектование
     * (см. ZnpKind.ofNullable).
     *
     * Для заказа верхнего уровня значение не имеет смысла и игнорируется.
     */
    private String znpKind;

    /*
     * Изделие группового или ремонтного заказа.
     *
     * Обязательность проверяет сервис: поле нужно не всем видам, а
     * аннотация @NotNull отклонила бы корректную форму комплектования,
     * где состава «изделием и количеством» нет.
     */
    private Long productClassifierId;

    /*
     * Количество заказанных изделий — тоже только для групповых и
     * ремонтных видов (см. productClassifierId). Дробное, как в позиции
     * заказа покупателя: единицы измерения различаются.
     */
    private BigDecimal quantity;

    /*
     * Техпроцесс, по которому выполняют групповой заказ (миграция V40).
     *
     * Как и изделие с количеством, обязательность проверяет сервис:
     * поле нужно только групповым видам (см. ZnpKind#requiresTechProcess),
     * а аннотация @NotNull отклонила бы корректную форму комплектования,
     * где маршрута нет — его операции живут у выпуска.
     */
    private Long techProcessId;

    /*
     * Комплектовочная операция выпуска.
     *
     * Аннотация @NotNull снята: операцию выбирает только заказ,
     * привязанный к выпуску (см. ZnpKind#isReleaseBound). Групповому
     * заказу наследовать операцию не от чего — вместо неё он ведёт
     * техпроцесс (techProcessId), и обязательность поля держит сервис
     * (ProductionOrderService#requireKittingOperation), как это уже
     * сделано для изделия, количества и маршрута.
     */
    private Long productionOperationId;

    /*
     * Приоритет группового заказа (миграция V41).
     *
     * Обязательность держит сервис: поле нужно только групповым и
     * ремонтным видам (см. ZnpKind#isGroupKind), а аннотация @NotNull
     * отклонила бы корректную форму комплектования, где приоритет
     * приходит вместе с заказом покупателя.
     */
    private Long priorityId;

    /*
     * Дата завершения группового заказа.
     *
     * Выпуск получает срок из заказа покупателя, самостоятельному
     * заказу ставить его нечем — без срока заказ не встанет в график,
     * поэтому для групповых видов поле обязательно (см. сервис).
     */
    @DateTimeFormat(pattern = "dd.MM.yyyy")
    private LocalDate dueDate;

    /*
     * Номера датчиков, в которые входит заказ-комплектующий.
     *
     * Серийники НЕ создаются здесь: их выпускает заказ верхнего уровня
     * (ЗП), а комплектующий лишь выбирается из уже выпущенных. Поэтому
     * список заполняется только для ЗНП и только значениями из
     * выбранного родителя — сервис проверяет принадлежность.
     *
     * Поле не размечено @NotEmpty: для заказа верхнего уровня оно
     * обязано оставаться пустым, а обязательность ЗНП проверяется
     * сервисом, где известен уровень заказа.
     *
     * СОХРАНЯЕТСЯ как плоский перечень датчиков: форма ЗНП нового
     * образца задаёт состав парами «датчик → операция» (serialOperations),
     * но этот список остаётся источником для тех мест, где операция одна
     * на весь заказ (старый сценарий и правка), и для обратной связи
     * контроллера. Сервис сверяет оба представления между собой.
     */
    private List<Long> serialIds = new ArrayList<>();

    /*
     * Состав заказа-комплектующего нового образца: пара «датчик →
     * операция комплектования» на каждый выбранный датчик.
     *
     * Нужен потому, что у ЗНП больше нет одной общей операции: работа
     * по каждому датчику выполняется операцией из техпроцесса ИМЕННО
     * этого датчика, и выбор операции различается по строкам таблицы
     * «датчик → операция». Spring привязывает список индексами
     * (serialOperations[0].serialId, serialOperations[0].operationId),
     * поэтому элемент — отдельный связываемый тип с пустым конструктором.
     *
     * operationId пуст, если для датчика операция ещё не выбрана; сервис
     * проверяет, что выбранная операция принадлежит техпроцессу датчика
     * и не занята другим заказом по этому же датчику.
     */
    private List<SerialOperation> serialOperations = new ArrayList<>();

    /*
     * Подтверждение повтора номера ЗНП.
     *
     * Номер ЗНП приходит из внешнего учёта, и один и тот же документ
     * может добираться датчиками постепенно: диспетчер заводит заказ,
     * а позже дописывает в него ещё датчики. Формально это повтор
     * номера, который уникальность базы отклонила бы, поэтому форма
     * предупреждает, а диспетчер явно подтверждает дописывание этим
     * флагом. Без подтверждения повтор отклоняется.
     */
    private boolean numberConfirmed;

    /*
     * Серийные номера, которые выпуск берёт из резерва заказа
     * покупателя, а не получает заново.
     *
     * Поле отдельное от {@link #serialIds} намеренно: там ЗНП выбирает
     * датчики среди УЖЕ ВЫПУЩЕННЫХ parent'ом, здесь выпуск подхватывает
     * номера, которые ещё не имеют хозяина. Значения похожи (id из
     * product_serials), смысл и проверки — противоположные, и один список
     * на оба случая заставил бы сервис угадывать режим по признаку
     * «корневой заказ или нет».
     *
     * Отмеченные диспетчером номера переиспользует
     * SerialIssueService#claimForRelease; остальные экземпляры позиции
     * получают номера как раньше.
     */
    private List<Long> releaseSerialIds = new ArrayList<>();

    @NotNull(message = "Укажите дату открытия заказа")
    @DateTimeFormat(pattern = "dd.MM.yyyy")
    private LocalDate orderDate;

    @Size(max = 2000, message = "Не более 2000 символов")
    private String note;

    private Long version;

    /*
     * Значения для повторного вывода формы: формат дд.мм.гггг задаётся
     * здесь, потому что диалект Thymeleaf javatime не подключён.
     *
     * Срока исполнения и статуса в форме нет сознательно: срок
     * подтягивается из заказа покупателя, а статус нового выпуска всегда
     * «Новый» и меняется только кнопками в карточке заказа.
     */
    public String getFormattedOrderDate() {
        return formatDate(orderDate);
    }

    /*
     * Вид ЗНП, разобранный из строки селектора.
     *
     * Шаблону он нужен, чтобы решить, какие поля показывать: перечень
     * серийников (комплектование) либо изделие с количеством
     * (групповые и ремонтные виды). Разбор тот же, что в сервисе, —
     * иначе форма и сервис разошлись бы уже на первом же неверном
     * значении.
     */
    public ZnpKind getResolvedKind() {
        return ZnpKind.ofNullable(znpKind);
    }

    /*
     * Выбран ли в форме заказ-комплектующий.
     *
     * Шаблон и JS опрашивают именно этот признак, а не наличие
     * родителя: до выбора конкретного выпуска диспетчер уже знает,
     * какой заказ заводит, и поля комплектующего (вид, номер, состав)
     * должны быть доступны сразу.
     *
     * При правке значение не важно — там уровень задаёт редактируемый
     * заказ, и шаблон переключает поля по нему.
     */
    public boolean isComponentLevel() {
        return LEVEL_COMPONENT.equalsIgnoreCase(
                orderLevel == null ? "" : orderLevel.trim()
        );
    }

    public String getFormattedQuantity() {
        return quantity == null
                ? ""
                : quantity.stripTrailingZeros().toPlainString();
    }

    /*
     * Плоский перечень датчиков, выведенный из пар «датчик → операция».
     *
     * Нужен, чтобы сервис сверил состав, заданный новой таблицей, со
     * старым списком serialIds, и чтобы места, где достаточно только
     * датчиков (проверка обязательности состава, снятие отвязанных
     * связей), читали один источник независимо от того, каким способом
     * форма заполнена.
     */
    public List<Long> resolvedSerialIds() {
        List<Long> ids = new ArrayList<>();

        for (SerialOperation pair : serialOperations) {
            if (pair != null && pair.getSerialId() != null) {
                ids.add(pair.getSerialId());
            }
        }

        if (!ids.isEmpty()) {
            return ids;
        }

        return serialIds == null ? List.of() : serialIds;
    }

    private static String formatDate(LocalDate date) {
        return date == null ? "" : date.format(DATE_FORMATTER);
    }

    /**
     * Пара «датчик → операция комплектования» одной строки таблицы
     * состава ЗНП.
     *
     * Связываемый тип: Spring заполняет поля индексами из формы, поэтому
     * нужны пустой конструктор и сеттеры (Lombok).
     */
    @Getter
    @Setter
    @NoArgsConstructor
    public static class SerialOperation {

        /* Датчик (ProductSerial.id), к которому относится строка. */
        private Long serialId;

        /*
         * Операция комплектования из техпроцесса этого датчика
         * (Operation.id). Пуста, пока диспетчер не выбрал операцию.
         */
        private Long operationId;

        public SerialOperation(Long serialId, Long operationId) {
            this.serialId = serialId;
            this.operationId = operationId;
        }
    }
}