package ru.company.production.dto;

import ru.company.production.entity.KittingType;
import ru.company.production.entity.ZnpKind;

/**
 * Вид группового ЗНП, предложенный маршрутом.
 *
 * Диспетчер больше не выбирает вид кнопкой на странице списка: вид
 * выводится из ПЕРВОЙ по техпроцессу операции, потому что именно она
 * решает, чем заказ укомплектован и кто его комплектует. Маршрут с
 * «Комплектованием ячеек» склада — это выпуск новых ячеек, тот же тип
 * операции в Бюро технического контроля — ремонт. Одинаковый текст
 * кнопки давал бы два разных документа, и различие держат здесь.
 *
 * Запись, а не enum: у предложения два независимых поля (вид и тип
 * комплектования) и признак пригодности маршрута, а набор таких
 * комбинаций — свойство настроенных маршрутов, а не справочника.
 *
 * @param kind                вид заказа, который задала первая
 *                            операция; null, если маршрут вид задать
 *                            не может
 * @param kittingType         тип комплектования для вида на ячейки
 *                            (подсборки — {@link KittingType#SUBASSEMBLY},
 *                            ячейки — {@code null}); для ремонтных
 *                            видов всегда {@code null}
 * @param operationLabel      первая операция маршрута в подписи
 *                            («Комплектование ячеек — Склад
 *                            полуфабрикатов») — по ней диспетчер
 *                            понимает, откуда взялся вид
 * @param message             пояснение для пустого или спорного
 *                            выбора: почему маршрут не задаёт вид,
 *                            либо чем предложенный вид отличается от
 *                            обычного комплектования
 * @param ownerUnitCode       код подразделения первой операции —
 *                            склад или БТК; нужен подписи формы, а не
 *                            решению сервиса
 */
public record GroupZnpKindProposal(
        ZnpKind kind,
        KittingType kittingType,
        String operationLabel,
        String message,
        String ownerUnitCode
) {

    /**
     * Задаёт ли маршрут вид заказа.
     *
     * Отрицание читают и шаблон (показывать ли подсказку), и сервис
     * (отклонять ли сохранение): проверка обязательна именно здесь, а
     * не в двух местах разными способами.
     *
     * Имя с префиксом isApplicable: форма отрисовывается и через
     * Thymeleaf, и через JSON ответа endpoint'а, а Jackson показывает
     * свойство только геттеру с get/is — метод без префикса ушёл бы из
     * ответа, и скрипт счёл бы любой маршрут непригодным.
     */
    public boolean isApplicable() {
        return kind != null;
    }

    /**
     * Название предложенного вида для подписи формы и JSON-ответа.
     *
     * Метод, а не компонент записи: название целиком следует из {@code
     * kind}, и держать его в конструкторе значило бы передавать в каждый
     * вызов значение, которое можно взять из уже переданного.
     */
    public String getKindDisplayName() {
        return kind == null ? null : kind.getDisplayName();
    }

    /**
     * Предложение «маршрут вид не задаёт» с объяснением причины.
     */
    public static GroupZnpKindProposal notApplicable(String operationLabel,
                                                     String message) {

        return new GroupZnpKindProposal(
                null, null, operationLabel, message, null
        );
    }
}
