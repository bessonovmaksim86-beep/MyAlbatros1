package ru.company.production.dto;

import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Данные приёмки на склад полуфабрикатов партии, вернувшейся из БВК.
 *
 * Номера передаются текстом, а не списком идентификаторов: кладовщик
 * вводит их с этикетки или сканера, и поле остаётся полем ввода.
 * Разбор и сверка с партией — задача сервиса, которому известен и
 * диапазон номеров партии, и перечень её брака.
 *
 * В отличие от выборочного контроля БВК, здесь перечень обязан быть
 * подмножеством ячеек, контроль прошедших: ячейку, отсеянную на брак,
 * принять на склад нельзя, и проверяет это именно сервис, а не форма.
 */
@Getter
@Setter
@NoArgsConstructor
public class BvkAcceptanceForm {

    /** Партия: идентификатор приходит строкой из скрытого поля формы. */
    @NotNull(message = "Партия не выбрана")
    private Long batchId;

    /** Принимаемые номера ячеек: по одному в строке. */
    @Size(max = 20000, message = "Список номеров слишком длинный")
    private String cellNumbersText;

    /**
     * Отметка «отметить все номера ячеек».
     *
     * Работает как «все ячейки партии» в карточке БВК: перечень
     * подставляется сервером полный (за вычетом брака), а поле ввода
     * на экране закрывается от правки. Проведение по этой отметке
     * требует подтверждения — ошибочный состав партии исправить нельзя.
     */
    private boolean allCells;
}
