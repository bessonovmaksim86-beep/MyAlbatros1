package ru.company.production.dto;

import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.ArrayList;
import java.util.List;

/**
 * Форма заказа на ремонт (ЗНП).
 *
 * Ячейки приходят строками «id группы|полный номер»: пара нужна целиком,
 * потому что один и тот же номер мог быть забракован в разных группах с
 * разными причинами, а заказ обязан ссылаться на конкретную группу.
 *
 * Исполнитель заказа выбирается одним из двух способов: ремонт ведёт
 * поставщик (написание из справочника склада) или собственные силы —
 * СДП, и тогда заказ привязывают к маршруту, по которому ремонт выполняют
 * (техпроцессу). Оба способа взаимоисключающи: заказ либо уходит
 * поставщику, либо остаётся на предприятии.
 *
 * Номер вводит руководитель службы: бумажный ЗНП заводят по журналу
 * подразделения, и автономер «первого свободного» расходился бы с
 * журналом. Пустое поле означает «подобрать номер автоматически».
 */
@Getter
@Setter
@NoArgsConstructor
public class RepairOrderForm {

    /** Ячейки: «groupId|121200023». */
    private List<String> cells = new ArrayList<>();

    /**
     * Номер ЗНП из журнала подразделения.
     *
     * Необязателен: при пустом значении сервис подбирает ближайший
     * свободный номер ряда текущего года.
     */
    @Size(max = 50, message = "Номер ЗНП не длиннее 50 знаков")
    private String number;

    /** Идентификатор поставщика из справочника склада. */
    private Long supplierId;

    /** Написание поставщика, выбранное из справочника. */
    private String supplierChoice;

    @Size(max = 255, message = "Наименование поставщика не длиннее 255 знаков")
    private String supplierName;

    /** Ремонт выполняют собственными силами (СДП), а не поставщик. */
    private boolean bySdp;

    /** Маршрут, по которому СДП выполняет ремонт. */
    private Long techProcessId;

    /** Ремонт выдан с выдачей комплектации. */
    private boolean kitsIssue;

    /** Перечень компонентов для выдачи — свободный текст. */
    @Size(max = 2000, message = "Перечень комплектации не длиннее 2000 знаков")
    private String kitsList;

    /**
     * Вид заказа: ремонт ячеек или ремонт подсборок.
     *
     * Поле передаёт форма, но заказу вид ставят по составу отмеченных
     * ячеек (см. QualityService.create): однородный состав предопределяет
     * вид, и выбор вручную расходился бы с составом. Строку держат для
     * подсветки в форме и для совместимости с разметкой страницы.
     */
    private String orderType;

    @Size(max = 2000, message = "Примечание не длиннее 2000 знаков")
    private String note;

    /**
     * Подсказка формы: «другое» написание поставщика вписывают вручную.
     *
     * Отдельного чекбокса нет — признак выводится из выбора в списке,
     * чтобы форма не предлагала противоречивые состояния.
     */
    public boolean isCustomSupplier() {
        return "CUSTOM".equalsIgnoreCase(
                supplierChoice == null ? "" : supplierChoice.trim()
        );
    }
}