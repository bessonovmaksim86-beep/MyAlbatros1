package ru.company.production.config;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;

/**
 * Параметры подключения к базе 1С (PostgreSQL).
 *
 * Обмен с 1С выключен по умолчанию. Причина не в осторожности: база
 * 1С стоит на другой машине, её адрес и учётные данные известны только
 * на рабочем месте, а попытка соединиться при запуске без них означала
 * бы ошибку в логе на каждом старте приложения.
 *
 * Источник данных здесь НЕ объявляется бином Spring. {@code
 * DataSourceAutoConfiguration} отключается, как только в контексте
 * появляется собственный {@code DataSource}, и тогда основная база
 * приложения (MySQL) перестала бы создаваться вовсе: приложение не
 * стартовало бы, а не «просто не соединялось с 1С». Поэтому соединение
 * открывает {@code OneCJdbcClient} через {@code DriverManager} — на
 * время одного запроса, после чего оно закрывается.
 *
 * Пароль задаётся только переменной окружения и в файле не хранится.
 */
@Getter
@Setter
@Component
@ConfigurationProperties(prefix = "application.onec")
public class OneCProperties {

    /** Разрешает обращение к базе 1С из раздела интеграции. */
    private boolean enabled = false;

    /**
     * JDBC-адрес базы 1С.
     *
     * База 1С на PostgreSQL обслуживается сервером 1С, порт по
     * умолчанию 5432; имя базы создаётся при добавлении базы 1С и
     * обычно выглядит как набор из восьми шестнадцатеричных цифр.
     */
    private String url = "";

    /** Имя пользователя базы 1С. */
    private String username = "";

    /** Пароль пользователя базы 1С. */
    private String password = "";

    /**
     * Запрос выбора заказов на производство (ЗП) из базы 1С.
     *
     * Требуется ровно пять колонок в таком порядке: номер документа,
     * дата документа, номер связанного заказа покупателя, наименование
     * контрагента, статус. Порядок, а не имена, потому что таблицы
     * конфигурации 1С называются по-разному в разных базах: имена
     * колонок узнать заранее нельзя, а порядок задаёт сам администратор
     * в настройке.
     *
     * Пустое значение — выгрузка берётся из собственной базы
     * приложения, где структура известна.
     */
    private String zpQuery = "";

    /** Ограничение числа строк выдачи: защита от выгрузки всей базы. */
    private int maxRows = 500;

    /** Сколько секунд ждать ответа сервера 1С. */
    private int connectTimeoutSeconds = 10;

    /** Готовно ли соединение: включено и задан адрес. */
    public boolean isConfigured() {
        return enabled && url != null && !url.isBlank();
    }
}
