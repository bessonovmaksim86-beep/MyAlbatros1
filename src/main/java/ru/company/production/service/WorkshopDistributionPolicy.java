package ru.company.production.service;

import ru.company.production.entity.Role;

import java.util.Set;

/**
 * Ролевая политика распределения работ.
 *
 * <p>Здесь собраны наборы ролей, которые {@code WorkshopDistributionService}
 * держал тремя отдельными константами: {@code SUPERVISOR_ROLES},
 * {@code UNIT_POOL_ROLES} и {@code NO_DISTRIBUTION_ROLES}. Раздельное
 * хранение стоило рассинхронизации: набор правили в одном месте, а
 * зависевший от него признак оставался прежним, и пользователь либо
 * получал пункт меню в 403, либо вход в раздел без права проводить
 * закрепление.
 *
 * <p>Наборы оперируют {@link Role} напрямую, а не строками: расхождение
 * с enum становится ошибкой сборки. Кириллические имена ролей склада
 * комплектации при этом остаются ловушкой для любых строковых
 * сравнений — их здесь нет намеренно.
 *
 * <p>Методы статичны и не обращаются к репозиториям: признаки читают
 * только роль учётной записи, поэтому их можно утверждать тестом без
 * контекста приложения. Обоснование состава наборов —
 * {@code docs/security-access.md}, разделы 4 и 5.
 */
public final class WorkshopDistributionPolicy {

    /*
     * Руководящие роли: те, кому планировщик отдаёт получение
     * комплектации своего подразделения как личную работу.
     *
     * Рядом с мастерами цехов, складов и бюро стоят начальники
     * технологического бюро и диспетчерского отдела, руководитель
     * службы качества — у них нет цехового модуля, но операции
     * своего подразделения (в том числе получение комплектации)
     * закрепляются именно за ними, и распределять их больше некому.
     */
    private static final Set<Role> SUPERVISOR_ROLES = Set.of(
            Role.SDP_SPP_MASTER,
            Role.SDP_SA_MASTER,
            Role.SDP_SC_MASTER,
            Role.SDP_ST_MASTER,
            Role.OMTSIK_MASTER,
            Role.OMTSIK_С_MASTER,
            Role.BVK_MASTER,
            Role.BTK_MASTER,
            Role.SGP_MASTER,
            Role.SGM_MASTER,
            Role.SDP_SERVICE_HEAD_TECHNOLOGY,
            Role.SDP_SERVICE_HEAD_DISPATCHER,
            Role.DISPATCHER,
            Role.SK_GENERAL
    );

    /*
     * Подразделения, где работу не распределяют: бюро входного контроля
     * и бюро технического контроля.
     *
     * Контролёр бюро берёт любую работу из перечня бюро, а планировщик
     * закрепляет строку графика за подразделением, а не за человеком,
     * поэтому и меню, и право проведения здесь считаются по
     * подразделению, а не по executor_id.
     */
    private static final Set<Role> NO_DISTRIBUTION_ROLES = Set.of(
            Role.BVK_MASTER,
            Role.BTK_MASTER
    );

    /*
     * Роли, в которых работу не распределяют: бюро входного контроля
     * и бюро технического контроля.
     *
     * БТК стоит в этом же наборе наравне с БВК: распределения работ
     * у него нет, и закрепление строки за конкретным контролёром
     * отрезало бы остальным доступ к её проведению.
     */
    private static final Set<Role> UNIT_POOL_ROLES = Set.of(
            Role.BVK_EXECUTOR,
            Role.BVK_MASTER,
            Role.BTK_EXECUTOR,
            Role.BTK_MASTER,
            Role.SK_GENERAL
    );

    private WorkshopDistributionPolicy() {
    }

    /**
     * Является ли роль руководящей.
     *
     * <p>Руководящая роль — та, кому планировщик отдаёт получение
     * комплектации своего подразделения как личную работу. В сервисе
     * это признак {@code isSupervisor}, на котором держатся «Мои
     * операции» руководителя, счётчик меню и проверка права
     * проведения закрепления.
     *
     * @param role роль учётной записи
     * @return {@code true}, если роль руководящая
     */
    public static boolean isSupervisor(Role role) {
        return role != null && SUPERVISOR_ROLES.contains(role);
    }

    /**
     * Открыт ли пользователю раздел распределения работ.
     *
     * <p>Признак один на меню, уведомления и право проводить
     * закрепление: пункт в меню и доступ к адресу задаются им же,
     * иначе меню звало бы в 403.
     *
     * <p>От {@link #isSupervisor} признак отличается на ролях бюро:
     * они руководящие и свои личные работы получения комплектации
     * ведут, но распределять им нечего — строку бюро планировщик
     * закрепляет за подразделением, и любой контролёр берёт её сам.
     *
     * @param role роль учётной записи
     * @return {@code true}, если раздел распределения открыт
     */
    public static boolean canDistribute(Role role) {
        return isSupervisor(role) && !NO_DISTRIBUTION_ROLES.contains(role);
    }

    /**
     * Берёт ли пользователь работу из перечня подразделения.
     *
     * <p>В бюро входного контроля и бюро технического контроля работу
     * не распределяют: планировщик закрепляет строку графика за
     * подразделением, а любой контролёр берёт её из перечня бюро
     * сам. Руководитель бюро и руководитель службы качества видят
     * тот же перечень целиком.
     *
     * <p>Это признак, на котором держится логика «Мои операции»
     * руководителя для бюро: если он в пуле, строка берётся по
     * подразделению, а не по конкретному человеку.
     *
     * @param role роль учётной записи
     * @return {@code true}, если работа берётся из пула подразделения
     */
    public static boolean isUnitPool(Role role) {
        return role != null && UNIT_POOL_ROLES.contains(role);
    }
}
