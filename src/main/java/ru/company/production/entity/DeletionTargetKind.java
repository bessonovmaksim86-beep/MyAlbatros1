package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Тип записи, удалённой администратором.
 *
 * Перечень замкнут осознанно: раздел «Очистка данных» умеет снимать с
 * работы ровно те объекты, вокруг которых построен граф внешних
 * ключей, — заказ на производство и партию оприходования. Заказы
 * покупателя и справочники удаляют их собственные разделы, и запись
 * об удалении классификатора в этом журнале означала бы два журнала
 * на одно действие.
 *
 * Значение пишут в журнал строкой (миграция V73,
 * chk_admin_deletion_target_kind), поэтому порядок и имена элементов
 * менять нельзя — старые строки журнала должны читаться и после
 * появления нового типа.
 */
@Getter
@RequiredArgsConstructor
public enum DeletionTargetKind {

    /** Заказ на производство: и выпуск (ЗП), и заказ-комплектующий (ЗНП). */
    PRODUCTION_ORDER("Заказ на производство"),

    /** Партия оприходования склада полуфабрикатов. */
    RECEIVING_BATCH("Партия оприходования");

    private final String displayName;
}
