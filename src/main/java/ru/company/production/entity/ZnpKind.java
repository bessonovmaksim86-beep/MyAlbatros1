package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

import java.util.Arrays;
import java.util.List;

/**
 * Вид заказа-комплектующего (ЗНП).
 *
 * Диспетчер заводит ЗНП не только чтобы укомплектовать датчик: тот же
 * документ нужен, чтобы заявить группу ячеек или приборов и чтобы
 * отдать в ремонт ячейку либо подсборку. Смысл у этих заказов разный,
 * поэтому различие фиксируют отдельно от уровня дерева: уровень
 * (ЗП/ЗНП) отвечает на вопрос «входит заказ внутрь изделия или нет»,
 * вид — «зачем заказ заведён».
 *
 * Комплектующие, заведённые до появления выбора, читаются как
 * {@link #KITTING}: именно этот вид и оформлялся раньше (миграция V21),
 * и других в реестре нет.
 *
 * НАИМЕНОВАНИЯ СОВПАДАЮТ С НАДПИСЯМИ КНОПОК СОЗДАНИЯ. Кнопка страницы
 * списка берётся из {@link #getCreateButtonLabel()}, поэтому переименование
 * вида меняет и кнопку, и колонку «Уровень» списка, и заголовок формы —
 * из одного места, а не из трёх.
 */
@Getter
@RequiredArgsConstructor
public enum ZnpKind {

    /**
     * ЗНП на комплектование — прежний и единственный вид до V37.
     *
     * Состав заказа — конкретные серийные номера родительского выпуска:
     * диспетчер отмечает датчики, в которые заказ входит.
     */
    KITTING(
            "ЗНП на комплектование датчиков и систем",
            "отмечаете датчики выпуска"
    ),

    /**
     * Групповой ЗНП на ячейки: заказ сразу на группу ячеек одного
     * наименования, поэтому указывается изделие и количество, а не
     * перечень номеров.
     */
    GROUP_CELL(
            "Групповой ЗНП на ячейки",
            "изделие и количество"
    ),

    /** Групповой ЗНП на приборы — тот же принцип, изделия «Прибор». */
    GROUP_DEVICE(
            "Групповой ЗНП на приборы",
            "изделие и количество"
    ),

    /**
     * ЗНП на ремонт ячеек.
     *
     * Классификатор здесь — изделие типа «Ячейка»: подсборка и ячейка
     * различаются стадией движения, а не типом классификатора
     * (см. {@link QuarantineCellKind}), поэтому справочник для обоих
     * ремонтных видов общий, а различие несёт сам вид заказа.
     */
    CELL_REPAIR(
            "Групповой ЗНП на ремонт ячеек",
            "изделие и количество"
    ),

    /** ЗНП на ремонт подсборок. */
    SUBASSEMBLY_REPAIR(
            "Групповой ЗНП на ремонт подсборок",
            "изделие и количество"
    );

    private final String displayName;

    /**
     * Короткая подсказка о том, чем задан состав заказа.
     *
     * Нужна кнопкам создания ЗНП: выбор вида диспетчер делает до
     * открытия формы, и без пояснения различие «комплектование /
     * групповой» было видно только после перехода в форму.
     */
    private final String compositionHint;

    /**
     * Нужен ли заказу перечень конкретных серийных номеров.
     *
     * Один признак задаёт и поведение формы, и поведение сервиса:
     * у заказанных группой или на ремонт номеров нет — заказ описан
     * изделием и количеством, и привязывать его к серийникам не к чему.
     */
    public boolean isSerialBased() {
        return this == KITTING;
    }

    /**
     * Групповой ли заказ — то есть заводится ли он отдельно от
     * выпуска.
     *
     * К групповым относятся все виды, кроме комплектования: их
     * наименования начинаются со «Групповой ЗНП», и раздел диспетчерского
     * меню «Групповые ЗНП» построен именно по этому признаку — а не по
     * перечню из четырёх констант, куда при добавлении нового вида
     * забыли бы дописать строку.
     */
    public boolean isGroupKind() {
        return this != KITTING;
    }

    /**
     * Привязан ли заказ к выпуску — то есть заводятся ли у него
     * заказ покупателя и комплектовочная операция.
     *
     * Оба поля появляются из одного обстоятельства: заказ вписывается
     * внутрь выпуска, заказчик у него наследуется от этого выпуска, а
     * срок исполнения подтягивается из его заказа покупателя.
     *
     * Признак отдельный от {@link #isSerialBased()}, хотя набор значений
     * у них сейчас совпадает: серийники отвечают за состав заказа, а
     * заказчик с операцией — за его привязку к выпуску. Групповые виды
     * (V38) самостоятельны: заказчика у них выбирать не из чего, а
     * комплектовочная операция им не выполняется — вместо неё заказ
     * ведёт техпроцесс (см. {@link #requiresTechProcess()}).
     */
    public boolean isReleaseBound() {
        return this == KITTING;
    }

    /**
     * Выбирается ли для заказа техпроцесс.
     *
     * Групповой заказ задаётся изделием и количеством, и работы по нему
     * идут по маршруту этого изделия — диспетчер выбирает техпроцесс
     * сразу при заведении. Комплектованию маршрут не назначается: его
     * операции живут у выпуска, внутрь которого заказ входит.
     *
     * Обратный признак к {@link #isReleaseBound()} — держится отдельным
     * методом, чтобы шаблон и сервис спрашивали «показывать ли выбор
     * техпроцесса», а не выводили это из привязки к выпуску.
     */
    public boolean requiresTechProcess() {
        return this != KITTING;
    }

    /**
     * Ремонтный ли заказ — то есть заявлен ли он на ячейки или
     * подсборки из изолятора брака.
     *
     * Признак нужен бюро входного контроля: комплектование ремонтных
     * ячеек/подсборок отбирает ЗНП именно по ремонтным видам, а не по
     * перечню констант в запросе — новый ремонтный вид попадёт в
     * отбор одной правкой enum.
     */
    public boolean isRepairKind() {
        return this == CELL_REPAIR || this == SUBASSEMBLY_REPAIR;
    }

    /**
     * Виды, образующие раздел «Групповые ЗНП».
     */
    public static List<ZnpKind> groupKinds() {
        return Arrays.stream(values())
                .filter(ZnpKind::isGroupKind)
                .toList();
    }

    /**
     * Ремонтные виды — набор для отбора ЗНП на комплектование
     * (см. {@link #isRepairKind()}).
     */
    public static List<ZnpKind> repairKinds() {
        return Arrays.stream(values())
                .filter(ZnpKind::isRepairKind)
                .toList();
    }

    /**
     * Виды, остающиеся в разделе «Заказы на производство».
     *
     * Обратное к groupKinds(): сюда попадают заказы, состав которых задан
     * серийными номерами выпуска, а не изделием с количеством — то есть
     * ровно комплектование. Заказ верхнего уровня (ЗП) вида не выбирает и
     * в базе всегда носит KITTING как значение по умолчанию
     * (см. ProductionOrder#znpKind), поэтому отбор по этому набору отдаёт
     * и выпуски, и их комплектующие и не требует отдельного условия по
     * родителю.
     *
     * Список считается от того же признака, что и раздел групповых, —
     * иначе новый вид оказался бы не показан ни на одной из двух страниц.
     */
    public static List<ZnpKind> productionOrderKinds() {
        return Arrays.stream(values())
                .filter(kind -> !kind.isGroupKind())
                .toList();
    }

    /**
     * Надпись кнопки создания заказа этого вида.
     *
     * Кнопки вывода вида на странице списка и в карточке выпуска
     * строятся из одного поля, а не из текста, переписанного в двух
     * шаблонах: иначе переименование вида обновило бы список и
     * оставило бы карточку со старым названием.
     *
     * Слово «Создать» из надписи убрано: кнопки стоят в блоке создания
     * и под заголовком «Заказы на производство», где переход уже понятен
     * из контекста, а приставка лишь раздувала каждую из пяти кнопок и
     * ломала сетку группы.
     */
    public String getCreateButtonLabel() {
        return displayName;
    }

    /**
     * Изделие какого типа выбирают для заказа этого вида.
     *
     * null — изделие не выбирается (комплектование: там состав
     * образуется из серийников выпуска).
     */
    public ProductType requiredProductType() {
        return switch (this) {
            case GROUP_CELL, CELL_REPAIR, SUBASSEMBLY_REPAIR ->
                    ProductType.CELL;
            case GROUP_DEVICE -> ProductType.DEVICE;
            case KITTING -> null;
        };
    }

    /**
     * Подпись справочника изделий в форме ЗНП.
     *
     * Вид выбран кнопкой до открытия формы, поэтому в форме поле
     * называется тем, что диспетчер в нём увидит: «Список приборов»
     * или «Список ячеек», а не нейтральным «Изделие заказа».
     */
    public String getClassifierListLabel() {
        return requiredProductType() == ProductType.DEVICE
                ? "Список приборов"
                : "Список ячеек";
    }

    /**
     * Вид по имени из формы; пустое или неизвестное значение —
     * комплектование.
     *
     * Возврат KITTING, а не null, сознательный: комплектование — вид
     * всех заказов, заведённых до появления выбора, и форма, снятая со
     * старой страницы, обязана сохранить именно прежнее поведение.
     */
    public static ZnpKind ofNullable(String value) {
        if (value == null || value.isBlank()) {
            return KITTING;
        }

        try {
            return valueOf(value.trim().toUpperCase());
        } catch (IllegalArgumentException ignored) {
            return KITTING;
        }
    }
}