package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Вид контроля в журнале несерийных комплектующих.
 *
 * Раздел заведён под входной контроль, поэтому значение одно и в
 * форме оно не выбирается: журнал не должен смешивать виды, как это
 * делает бумажный бланк, где в одной колонке читаются и «Входной»,
 * и «Операционный».
 *
 * Перечисление оставлено отдельным, а не константой-строкой, по той
 * же причине, что и {@link InputControlType}: колонка в журнале
 * обязана содержать подписанное значение, а не произвольный текст,
 * иначе отбор по виду контроля собирался бы разбором строк.
 */
@Getter
@RequiredArgsConstructor
public enum JournalControlType {

    INPUT("Входной");

    private final String displayName;
}
