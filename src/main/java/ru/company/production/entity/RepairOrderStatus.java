package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Статус заказа на ремонт (ЗНП).
 *
 * Набор короткий и отличается от {@link ProductionOrderStatus}: у
 * заказа на ремонт нет «частично выполнен» — ремонт ячейки принимают
 * целиком по акту, а не по числу отремонтированных экземпляров.
 */
@Getter
@RequiredArgsConstructor
public enum RepairOrderStatus {

    NEW("Заявка создана", "draft"),

    IN_WORK("Набор состава", "work"),

    /**
     * Состав набран, заявка вернулась диспетчеру.
     *
     * ЗНП проходит через двух исполнителей: диспетчер заводит заявку
     * (номер, тип изделий, классификатор), служба качества набирает
     * состав из изолятора брака, после чего заявка ждёт у диспетчера
     * техпроцесса и места в графике. Остановку между этими стадиями
     * нельзя выразить статусом «в работе»: по «в работе» не понять,
     * кто сейчас держит документ.
     */
    RETURNED("Возвращена диспетчеру", "done"),

    DONE("Выполнен", "done"),

    CANCELLED("Отменён", "deleted");

    private final String displayName;

    /** Модификатор CSS-класса бейджа статуса. */
    private final String badgeClass;
}
