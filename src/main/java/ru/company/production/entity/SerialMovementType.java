package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Событие перемещения ячейки вокруг неизменного номера.
 *
 * Тип описывает «где побывал номер», а не «повторно ли»: повторность
 * цикла — производная от хронологии (сколько QUARANTINED прошло по
 * номеру), отдельного типа RE_QUARANTINED не заводим — иначе CHECK
 * разрастался бы, а «число циклов брака» всё равно считается COUNT'ом.
 */
@Getter
@RequiredArgsConstructor
public enum SerialMovementType {

    /*
     * Начало пути номера.
     *
     * RECEIVED — партию оприходовал склад (CellReceivingService), ISSUED —
     * номер выдал выпуск (ProductionOrderService). Разные начала, но один
     * смысл: с этого момента номер существует как изделие, и паспорт без
     * этой строки начинался бы с середины.
     */
    RECEIVED("Оприходована складом", "muted"),
    ISSUED("Выпущена производством", "muted"),

    /*
     * Отметка БВК о самом изделии, а не о партии.
     *
     * Карточка входного контроля закрывается по партии, а ячейки отмечают
     * поштучно: без этой строки в паспорте ячейки не было бы видно, что
     * она контроль прошла, — отметка жила бы только в колонках реестра,
     * которые следующее движение перечёркивает.
     */
    INPUT_CONTROL_PASSED("Прошла входной контроль", "ok"),

    QUARANTINED("Перемещена в изолятор брака", "danger"),
    RETURNED_TO_SUPPLIER("Возвращена поставщику", "attention"),
    REPAIR_ORDERED("Включена в ремонтный ЗНП", "attention"),
    REPAIR_DONE("Ремонт принят", "ok"),

    /*
     * Ячейка взята из изолятора в ремонтный заказ-комплектующий
     * силами бюро входного контроля (V52).
     *
     * Пара к REPAIR_ORDERED: тот тип фиксирует намерение (диспетчер
     * включил номер в заказ на ремонт), этот — событие (БВК реально
     * снял ячейку с изолятора и провёл по комплектовочной операции).
     * Без него между «Ремонт принят» и исчезновением из изолятора
     * образовывалась дыра: по журналу нельзя было сказать, кто и когда
     * забрал ячейку в работу.
     */
    KITTED_TO_REPAIR_ZNP("Взята в ремонтный ЗНП", "ok"),

    REPAIR_CANCELLED("Ремонтный ЗНП отменён", "muted"),
    IN_PRODUCTION("Вошла в выпуск производства", "muted"),
    ACCEPTED("Принята на склад", "ok"),

    /*
     * Подсборку отметили готовой ячейкой (V75).
     *
     * Отличается от ACCEPTED: та отметка кладёт позицию на склад, но
     * изделие остаётся подсборкой, пока кладовщик не подтвердит его
     * готовность галочкой в «Приёмке с БВК» (или приёмкой в составе
     * ЗНП режима V72). Без отдельного события паспорт ячейки не
     * показывал бы, когда именно подсборка стала ячейкой, — а именно
     * этот момент открывает ей путь в комплектование.
     */
    CELL_READY("Отмечена готовой ячейкой", "ok"),

    /*
     * Ячейка покинула изолятор брака по решению бюро входного
     * контроля и передана на приёмку складу полуфабрикатов (V63).
     *
     * Отличается от ACCEPTED: то событие ставит кладовщик, когда
     * реально принял ячейку на склад, это — контролёр БВК, когда
     * выносит ячейку из изолятора. Между ними ячейка числится
     * «передана», и склад обязан её увидеть и проверить номера.
     */
    TRANSFERRED_TO_WAREHOUSE("Передана со склада изолятора", "attention"),

    /*
     * Склад вернул ячейку в изолятор брака: перемещение снято, потому
     * что ячейку не приняли (не тот номер, повреждена, передана ошибочно).
     *
     * Событие обязано существовать: строку QuarantineTransfer удаляют,
     * и без строки журнала возврат выглядел бы так, будто ячейку из
     * изолятора забрали в ремонт, — а она никуда не уходила.
     */
    RETURNED_TO_QUARANTINE("Возвращена складом в изолятор", "danger"),

    /*
     * Выпуск, выдавший номер, удалён: номер освобождён и вернулся в
     * свободный резерв.
     *
     * Отметка нужна, иначе паспорт показал бы выпуск, которого больше
     * нет, а освобождение номера осталось бы необъяснённым.
     */
    RELEASE_CANCELLED("Выпуск, выдавший номер, отменён", "muted");

    private final String displayName;

    /** Модификатор CSS-класса метки события. */
    private final String badgeClass;
}