package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Чем именно закончилось обращение к разделу «Очистка данных».
 *
 * Различие нужно не для статистики, а для разбора претензий: жёсткое
 * удаление стирает запись, а откат оприходования возвращает партию в
 * черновик и освобождает зарезервированные номера. По журналу обязано
 * быть видно, какого рода действие оставило базу без строк — иначе
 * «пропала партия» и «партия снова черновик» выглядели бы одинаково.
 */
@Getter
@RequiredArgsConstructor
public enum DeletionAction {

    /** Запись и связанные с ней строки удалены физически. */
    HARD_DELETE("Жёсткое удаление"),

    /**
     * Оприходование откачено: партия стала черновиком, внесённые
     * номера удалены из реестра и ряд нумерации освобождён.
     */
    RECEIVING_ROLLBACK("Откат оприходования");

    private final String displayName;
}
