package ru.company.production.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Тип комплектования группового заказа-комплектующего (миграция V72).
 *
 * Групповой ЗНП задан изделием и количеством, но в пределах одного и
 * того же изделия заказ может решать разные задачи: ячейку можно
 * выпустить заново, а можно собрать из уже готовых подсборок. Различие
 * не несёт ни новый вид (ZnpKind), ни новый классификатор — оно
 * описывает, ЧЕМ заказ укомплектован, поэтому заведено отдельным
 * признаком.
 *
 * Тип нужен складу: ЗНП «на изготовление ячеек из подсборок» проходит
 * через раздел «Приёмка ячеек» — кладовщик вводит номера подсборок,
 * которые дошли до склада, и приёмка делает их ячейками (отметка
 * accepted_at, тот же переход, что у приёмки партии после БВК).
 *
 * Поле остаётся NULL-разрешающим: тип задают не всем заказам, а только
 * тем, где склад участвует в укомплектовании. Пустое значение означает
 * «обычный групповой заказ», и старые строки (V37/V38) читаются именно
 * так, не требуя разметки.
 */
@Getter
@RequiredArgsConstructor
public enum KittingType {

    /**
     * Ячейки изготавливают из подсборок: заказ укомплектовывают
     * подсборками, лежащими на складе, а приёмка на склад переводит
     * каждую из них в статус ячейки.
     */
    SUBASSEMBLY("Изготовление ячеек из подсборок");

    private final String displayName;

    /**
     * Тип по имени из формы; пустое или неизвестное значение — {@code null}.
     *
     * В отличие от {@link ZnpKind#ofNullable} возврат пустой, а не
     * какое-то значение по умолчанию: отсутствие типа — осмысленное
     * состояние (заказ без складского комплектования), и подменять его
     * нельзя.
     */
    public static KittingType ofNullable(String value) {

        if (value == null || value.isBlank()) {
            return null;
        }

        try {
            return valueOf(value.trim().toUpperCase());
        } catch (IllegalArgumentException ignored) {
            return null;
        }
    }
}
